//! `JigsawPlacement`: builds a jigsaw structure from its start pool, attaching pool elements at
//! matching jigsaw blocks breadth first (by placement priority) while they fit the free space.

use std::collections::{BTreeMap, VecDeque};
use std::sync::Arc;

use vanillite_base::BlockPos;
use vanillite_base::random::LegacyRandom;
use vanillite_chunk::HeightmapKind;

use super::JigsawStructure;
use super::element::{Jigsaw, PoolElement, shuffle};
use super::pools::{PoolAliasLookup, TemplatePools};
use crate::generator::TerrainGenerator;
use crate::structure::pool::{JigsawJunction, PoolElementStructurePiece, Projection};
use crate::structure::{GenerationContext, GenerationStub, LevelHeight};
use crate::template::{BoundingBox, LiquidSettings, Rotation};

/// `JigsawPlacement.addPieces(context, startPool, startJigsaw, maxDepth, position,
/// doExpansionHack, projectStartToHeightmap, maxDistanceFromCenter, poolAliasLookup,
/// dimensionPadding, liquidSettings)`.
///
/// The centre piece is chosen here (drawing from the context random); the other pieces are
/// generated by the returned stub's consumer, after the start's biome was found valid.
pub fn add_pieces<'s>(
    structure: &'s JigsawStructure,
    ctx: &mut GenerationContext<'_>,
    position: BlockPos,
    aliases: PoolAliasLookup,
) -> Option<GenerationStub<'s>> {
    let pools = &structure.pools;
    let random = &mut ctx.random.random;
    let center_rotation = Rotation::random(random);
    let start_pool = structure.start_pool;
    let center_pool_id = if pools.is_registered(start_pool) {
        let aliased = aliases.lookup(start_pool);
        if pools.get(aliased).is_some() {
            aliased
        } else {
            start_pool
        }
    } else {
        start_pool
    };
    let center_element = pools.get(center_pool_id)?.random_template(random)?;
    if matches!(**center_element, PoolElement::Empty) {
        return None;
    }
    let anchored = match structure.start_jigsaw_name {
        Some(target) => {
            let mut jigsaws = Vec::new();
            center_element.shuffled_jigsaw_blocks(position, center_rotation, random, &mut jigsaws);
            // Vanilla logs an error when the start pool has no such jigsaw.
            jigsaws.iter().find(|j| j.name == Some(target))?.pos
        }
        None => position,
    };
    let local_anchor = BlockPos::new(
        anchored.x - position.x,
        anchored.y - position.y,
        anchored.z - position.z,
    );
    let adjusted = BlockPos::new(
        position.x - local_anchor.x,
        position.y - local_anchor.y,
        position.z - local_anchor.z,
    );
    let mut center_piece = PoolElementStructurePiece::new(
        Arc::clone(center_element),
        adjusted,
        center_element.ground_level_delta(),
        center_rotation,
        center_element.bounding_box(adjusted, center_rotation),
        structure.liquid_settings,
    );
    let bb = center_piece.base.bounding_box;
    let center_x = (bb.max_x() + bb.min_x()) / 2;
    let center_z = (bb.max_z() + bb.min_z()) / 2;
    let height = ctx.height;
    let bottom_y = match structure.project_start_to_heightmap {
        None => adjusted.y,
        Some(heightmap) => {
            if !ctx.could_structure_exist_in_column(
                center_x,
                center_z,
                height.min_y,
                height.max_y(),
            ) {
                return None;
            }
            position.y + ctx.first_free_height(center_x, center_z, heightmap)
        }
    };
    let old_absolute_ground_y = bb.min_y() + center_piece.ground_level_delta;
    center_piece.move_piece(0, bottom_y - old_absolute_ground_y, 0);
    // `box` is the centre piece's (mutable) box in Vanilla, so it is the moved one from here.
    let bb = center_piece.base.bounding_box;
    if structure.dimension_padding.is_start_too_close(height, &bb) {
        return None;
    }
    let center_y = bottom_y + local_anchor.y;
    let max_depth = structure.max_depth;
    Some(GenerationStub::lazy(
        BlockPos::new(center_x, center_y, center_z),
        move |builder, ctx| {
            // Vanilla adds the pieces only with a positive depth: a start of size 0 has none
            // (and so does not generate).
            if max_depth > 0 {
                let mut pieces = vec![center_piece];
                let horizontal = structure.max_distance_from_center.horizontal;
                let vertical = structure.max_distance_from_center.vertical;
                let padding = structure.dimension_padding;
                let outer = aabb_cells(
                    [
                        center_x - horizontal,
                        (center_y - vertical).max(height.min_y + padding.bottom),
                        center_z - horizontal,
                    ],
                    [
                        center_x + horizontal + 1,
                        (center_y + vertical + 1).min(height.max_y() + 1 - padding.top),
                        center_z + horizontal + 1,
                    ],
                );
                let mut free = FreeSpace::of(outer);
                free.subtract(bb);
                let mut placer = Placer {
                    pools,
                    aliases: &aliases,
                    max_depth,
                    expansion_hack: structure.use_expansion_hack,
                    liquid_settings: structure.liquid_settings,
                    generator: ctx.generator,
                    height,
                    random: &mut ctx.random.random,
                    pieces: &mut pieces,
                    frees: vec![free],
                    placing: SequencedPriorityQueue::new(),
                };
                placer.try_placing_children(0, FreeId(0), 0);
                while let Some(state) = placer.placing.next() {
                    placer.try_placing_children(state.piece, state.free, state.depth);
                }
                for piece in pieces {
                    builder.add_piece(Box::new(piece));
                }
            }
        },
    ))
}

/// The cells of `new AABB(min, max)` (which orders each axis) as a box, `None` when the box
/// has no volume (`Shapes.create` makes it empty).
fn aabb_cells(a: [i32; 3], b: [i32; 3]) -> Option<BoundingBox> {
    let min = [a[0].min(b[0]), a[1].min(b[1]), a[2].min(b[2])];
    let max = [a[0].max(b[0]), a[1].max(b[1]), a[2].max(b[2])];
    (min[0] < max[0] && min[1] < max[1] && min[2] < max[2])
        .then(|| BoundingBox::new(min[0], min[1], min[2], max[0] - 1, max[1] - 1, max[2] - 1))
}

/// The free space a piece may still be placed in (Vanilla's `MutableObject<VoxelShape>`).
///
/// Vanilla builds it as `Shapes.create(AABB)` of an outer box and subtracts piece boxes with
/// `Shapes.join(…, ONLY_FIRST)`; a piece fits when `Shapes.joinIsNotEmpty(free,
/// Shapes.create(AABB.of(box).deflate(0.25)), ONLY_SECOND)` is false. Every coordinate involved
/// is a multiple of 0.25, so the voxel shape operations are exact set operations (their 1e-7
/// tolerances never merge two coordinates), and with the test box deflated by a quarter block
/// the test is: every block cell of `box` lies in the outer box and in no subtracted box. This
/// keeps the outer box and the subtracted boxes instead of the voxel grid.
#[derive(Debug)]
struct FreeSpace {
    outer: Option<BoundingBox>,
    subtracted: Vec<BoundingBox>,
}

impl FreeSpace {
    /// `Shapes.create(AABB.of(bb))` (or an empty shape).
    fn of(outer: Option<BoundingBox>) -> Self {
        Self {
            outer,
            subtracted: Vec::new(),
        }
    }

    /// `free = Shapes.join(free, Shapes.create(AABB.of(bb)), BooleanOp.ONLY_FIRST)`.
    fn subtract(&mut self, bb: BoundingBox) {
        self.subtracted.push(bb);
    }

    /// `!Shapes.joinIsNotEmpty(free, Shapes.create(AABB.of(bb).deflate(0.25)), ONLY_SECOND)`.
    fn fits(&self, bb: &BoundingBox) -> bool {
        self.outer.is_some_and(|outer| {
            outer.min_x() <= bb.min_x()
                && outer.min_y() <= bb.min_y()
                && outer.min_z() <= bb.min_z()
                && bb.max_x() <= outer.max_x()
                && bb.max_y() <= outer.max_y()
                && bb.max_z() <= outer.max_z()
        }) && !self.subtracted.iter().any(|s| s.intersects(bb))
    }
}

/// Index of a [`FreeSpace`] of a [`Placer`] (free spaces are shared by the pieces placed in
/// them).
#[derive(Clone, Copy, Debug)]
struct FreeId(usize);

/// `JigsawPlacement.PieceState`.
#[derive(Debug)]
struct PieceState {
    /// Index of the piece in the piece list.
    piece: usize,
    free: FreeId,
    depth: i32,
}

/// `SequencedPriorityIterator`: the highest priority first, first in first out within one.
///
/// Vanilla caches the highest non-empty queue and, when it runs empty, searches the next one;
/// adding with a priority at least the cached one makes that the cached queue. That always
/// yields the head of the highest non-empty priority, which this does directly.
#[derive(Debug)]
struct SequencedPriorityQueue<T> {
    queues: BTreeMap<i32, VecDeque<T>>,
}

impl<T> SequencedPriorityQueue<T> {
    /// An empty queue.
    fn new() -> Self {
        Self {
            queues: BTreeMap::new(),
        }
    }

    /// `add(data, priority)`.
    fn add(&mut self, data: T, priority: i32) {
        self.queues.entry(priority).or_default().push_back(data);
    }

    /// `hasNext()`/`next()`.
    fn next(&mut self) -> Option<T> {
        let mut entry = self.queues.last_entry()?;
        let data = entry.get_mut().pop_front();
        if entry.get().is_empty() {
            entry.remove();
        }
        data
    }
}

/// `JigsawPlacement.Placer`.
struct Placer<'a> {
    pools: &'a TemplatePools,
    aliases: &'a PoolAliasLookup,
    max_depth: i32,
    expansion_hack: bool,
    liquid_settings: LiquidSettings,
    generator: &'a TerrainGenerator,
    height: LevelHeight,
    random: &'a mut LegacyRandom,
    pieces: &'a mut Vec<PoolElementStructurePiece>,
    frees: Vec<FreeSpace>,
    placing: SequencedPriorityQueue<PieceState>,
}

impl Placer<'_> {
    /// `getFirstFreeHeight(x, z, WORLD_SURFACE_WG, heightAccessor, randomState)`.
    fn first_free_height(&self, pos: BlockPos) -> i32 {
        self.generator
            .first_free_height(pos.x, pos.z, HeightmapKind::WorldSurfaceWg, self.height)
    }

    /// `tryPlacingChildren(sourcePiece, contextFree, depth, ...)`.
    fn try_placing_children(&mut self, source_index: usize, context_free: FreeId, depth: i32) {
        let pools = self.pools;
        let source = &self.pieces[source_index];
        let source_element = Arc::clone(&source.element);
        let source_projection = source_element.projection();
        let source_rigid = source_projection == Projection::Rigid;
        let source_bb = source.base.bounding_box;
        let source_ground_level_delta = source.ground_level_delta;
        let source_box_y = source_bb.min_y();
        let mut source_free: Option<FreeId> = None;
        let mut source_jigsaws = Vec::new();
        source_element.shuffled_jigsaw_blocks(
            source.position,
            source.rotation,
            self.random,
            &mut source_jigsaws,
        );
        let mut target_elements: Vec<&Arc<PoolElement>> = Vec::new();
        let mut target_jigsaws: Vec<Jigsaw> = Vec::new();
        'jigsaws: for source_jigsaw in &source_jigsaws {
            let source_direction = source_jigsaw.front;
            let source_jigsaw_pos = source_jigsaw.pos;
            let target_jigsaw_pos = source_jigsaw_pos.relative(source_direction);
            let source_jigsaw_local_y = source_jigsaw_pos.y - source_box_y;
            let mut source_jigsaw_base_height = None;
            let pool_id = self.aliases.lookup(source_jigsaw.pool);
            // Vanilla warns about missing or empty pools and skips the jigsaw.
            let Some(target_pool) = pools.get(pool_id) else {
                continue;
            };
            if target_pool.size() == 0 && !pools.is_empty_pool(pool_id) {
                continue;
            }
            let fallback_id = target_pool.fallback();
            let Some(fallback) = pools.get(fallback_id) else {
                continue;
            };
            if fallback.size() == 0 && !pools.is_empty_pool(fallback_id) {
                continue;
            }
            let children_free = if source_bb.is_inside(target_jigsaw_pos) {
                *source_free.get_or_insert_with(|| {
                    self.frees.push(FreeSpace::of(Some(source_bb)));
                    FreeId(self.frees.len() - 1)
                })
            } else {
                context_free
            };
            target_elements.clear();
            if depth != self.max_depth {
                target_pool.shuffled_templates(self.random, &mut target_elements);
            }
            fallback.shuffled_templates(self.random, &mut target_elements);
            let placement_priority = source_jigsaw.placement_priority;
            for &target_element in &target_elements {
                if matches!(**target_element, PoolElement::Empty) {
                    break;
                }
                let mut rotations = Rotation::ALL;
                shuffle(&mut rotations, self.random);
                for target_rotation in rotations {
                    target_jigsaws.clear();
                    target_element.shuffled_jigsaw_blocks(
                        BlockPos::ZERO,
                        target_rotation,
                        self.random,
                        &mut target_jigsaws,
                    );
                    let hack_box = target_element.bounding_box(BlockPos::ZERO, target_rotation);
                    let expand_to = if self.expansion_hack && hack_box.y_span() <= 16 {
                        self.expansion(&hack_box, &target_jigsaws)
                    } else {
                        0
                    };
                    for target_jigsaw in &target_jigsaws {
                        if !source_jigsaw.can_attach(target_jigsaw) {
                            continue;
                        }
                        let target_jigsaw_local_pos = target_jigsaw.pos;
                        let raw_target_box_pos = BlockPos::new(
                            target_jigsaw_pos.x - target_jigsaw_local_pos.x,
                            target_jigsaw_pos.y - target_jigsaw_local_pos.y,
                            target_jigsaw_pos.z - target_jigsaw_local_pos.z,
                        );
                        let raw_target_bb =
                            target_element.bounding_box(raw_target_box_pos, target_rotation);
                        let raw_target_y = raw_target_bb.min_y();
                        let target_projection = target_element.projection();
                        let target_rigid = target_projection == Projection::Rigid;
                        let target_jigsaw_local_y = target_jigsaw_local_pos.y;
                        let delta_y = source_jigsaw_local_y - target_jigsaw_local_y
                            + source_jigsaw.front.normal()[1];
                        let target_box_y = if source_rigid && target_rigid {
                            source_box_y + delta_y
                        } else {
                            let base = *source_jigsaw_base_height
                                .get_or_insert_with(|| self.first_free_height(source_jigsaw_pos));
                            base - target_jigsaw_local_y
                        };
                        let y_offset = target_box_y - raw_target_y;
                        let mut target_bb = raw_target_bb.moved(0, y_offset, 0);
                        let target_box_position = raw_target_box_pos.offset(0, y_offset, 0);
                        if expand_to > 0 {
                            let new_size =
                                (expand_to + 1).max(target_bb.max_y() - target_bb.min_y());
                            target_bb.encapsulate_pos(BlockPos::new(
                                target_bb.min_x(),
                                target_bb.min_y() + new_size,
                                target_bb.min_z(),
                            ));
                        }
                        if !self.frees[children_free.0].fits(&target_bb) {
                            continue;
                        }
                        self.frees[children_free.0].subtract(target_bb);
                        let target_ground_level_delta = if target_rigid {
                            source_ground_level_delta - delta_y
                        } else {
                            target_element.ground_level_delta()
                        };
                        let mut target_piece = PoolElementStructurePiece::new(
                            Arc::clone(target_element),
                            target_box_position,
                            target_ground_level_delta,
                            target_rotation,
                            target_bb,
                            self.liquid_settings,
                        );
                        let junction_y = if source_rigid {
                            source_box_y + source_jigsaw_local_y
                        } else if target_rigid {
                            target_box_y + target_jigsaw_local_y
                        } else {
                            let base = *source_jigsaw_base_height
                                .get_or_insert_with(|| self.first_free_height(source_jigsaw_pos));
                            base + delta_y / 2
                        };
                        self.pieces[source_index].junctions.push(JigsawJunction {
                            source_x: target_jigsaw_pos.x,
                            source_ground_y: junction_y - source_jigsaw_local_y
                                + source_ground_level_delta,
                            source_z: target_jigsaw_pos.z,
                            delta_y,
                            dest_projection: target_projection,
                        });
                        target_piece.junctions.push(JigsawJunction {
                            source_x: source_jigsaw_pos.x,
                            source_ground_y: junction_y - target_jigsaw_local_y
                                + target_ground_level_delta,
                            source_z: source_jigsaw_pos.z,
                            delta_y: -delta_y,
                            dest_projection: source_projection,
                        });
                        self.pieces.push(target_piece);
                        if depth < self.max_depth {
                            self.placing.add(
                                PieceState {
                                    piece: self.pieces.len() - 1,
                                    free: children_free,
                                    depth: depth + 1,
                                },
                                placement_priority,
                            );
                        }
                        continue 'jigsaws;
                    }
                }
            }
        }
    }

    /// The expansion hack: the largest y span of the pools (and their fallbacks) that the
    /// target's inward facing jigsaws name, 0 without any.
    fn expansion(&self, hack_box: &BoundingBox, target_jigsaws: &[Jigsaw]) -> i32 {
        let pools = self.pools;
        target_jigsaws
            .iter()
            .map(|jigsaw| {
                if !hack_box.is_inside(jigsaw.pos.relative(jigsaw.front)) {
                    return 0;
                }
                let child = pools.get(self.aliases.lookup(jigsaw.pool));
                let child_size = child.map_or(0, |p| p.max_size());
                let fallback_size = child
                    .and_then(|p| pools.get(p.fallback()))
                    .map_or(0, |p| p.max_size());
                child_size.max(fallback_size)
            })
            .max()
            .unwrap_or(0)
    }
}

#[cfg(test)]
mod tests {
    use vanillite_base::Direction;

    use super::*;

    #[test]
    fn priority_queue_pops_highest_first_in_insertion_order() {
        let mut queue = SequencedPriorityQueue::new();
        queue.add('a', 0);
        queue.add('b', 1);
        queue.add('c', 0);
        assert_eq!(queue.next(), Some('b'));
        queue.add('d', 2);
        queue.add('e', 0);
        let rest: Vec<char> = std::iter::from_fn(|| queue.next()).collect();
        assert_eq!(rest, ['d', 'a', 'c', 'e']);
    }

    #[test]
    fn free_space_is_outer_box_minus_pieces() {
        let mut free = FreeSpace::of(aabb_cells([0, 0, 0], [10, 10, 10]));
        free.subtract(BoundingBox::new(0, 0, 0, 4, 4, 4));
        assert!(free.fits(&BoundingBox::new(5, 0, 0, 9, 9, 9)));
        assert!(!free.fits(&BoundingBox::new(4, 0, 0, 9, 9, 9)));
        assert!(!free.fits(&BoundingBox::new(5, 0, 0, 10, 9, 9)));
        assert!(
            !FreeSpace::of(aabb_cells([0, 5, 0], [1, 5, 1]))
                .fits(&BoundingBox::new(0, 5, 0, 0, 5, 0))
        );
    }

    #[test]
    fn jigsaws_attach_face_to_face() {
        let jigsaw = |front, top, rollable| Jigsaw {
            pos: BlockPos::ZERO,
            front,
            top,
            rollable,
            name: None,
            target: super::super::pools::PoolsBuilder::new().symbol("minecraft:empty"),
            pool: super::super::pools::PoolsBuilder::new().empty_pool(),
            placement_priority: 0,
            selection_priority: 0,
        };
        let up = jigsaw(Direction::Up, Direction::North, true);
        assert!(up.can_attach(&jigsaw(Direction::Down, Direction::East, false)));
        let aligned = jigsaw(Direction::Up, Direction::North, false);
        assert!(!aligned.can_attach(&jigsaw(Direction::Down, Direction::East, false)));
        assert!(!up.can_attach(&jigsaw(Direction::Up, Direction::North, false)));
    }
}
