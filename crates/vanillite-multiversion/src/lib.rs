//! Multi-version layer (architecture 14.3): lets clients of older Minecraft versions join a
//! server that speaks only the newest protocol, like ViaVersion (whose code and mapping files
//! are not used: this is an own implementation).
//!
//! A connection whose handshake names an accepted older protocol gets an [`Adapter`]: a
//! serverbound and a clientbound half that rewrite packet bodies (`id` + fields, uncompressed)
//! between the client's version and the server's. The serverbound half sits between inflate
//! and decode, the clientbound half between encode and compression, so everything behind it
//! (limits, decoders, validation, the world) is unchanged. Each half follows the connection
//! state on its own from the packets it sees.
//!
//! Adapters chain: one [step](generated) per pair of adjacent versions (`X → X+1 → … →
//! current`). Every step's id tables (packets, static registries, block states, the
//! synchronised registry entries the older version knows) are generated by `cargo xtask
//! codegen` from `data/multiversion/<id>/` and `data/vanilla/`; the packets whose fields
//! changed are rewritten by hand in the step's module.
//!
//! Costs: clients on the current version have no adapter. Translated clients pay for their
//! own translation; packets shared by many receivers (chunks, broadcasts) are translated once
//! per older version and cached on the [`SharedPacket`](vanillite_protocol::SharedPacket).
//!
//! The crate is pure (no I/O) and runs in the server's network pipeline (`vanillite-net`) and
//! in `vanillite-proxy`.

