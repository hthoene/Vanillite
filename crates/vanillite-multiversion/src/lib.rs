/// A supported older version.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Version {
    /// Version name (`26.2`).
    pub id: &'static str,
    /// Protocol version.
    pub protocol: i32,
}

/// The older versions this build translates, newest first.
pub const SUPPORTED: &[Version] = &[Version {
    id: generated::v26_2::ID,
    protocol: generated::v26_2::PROTOCOL,
}];

// The newest step must end at the server's version: after a version switch the build fails
// here until the step from the previous version (kept by `version update --final`) is written.
const _: () = assert!(generated::v26_2::NEXT_PROTOCOL == vanillite_protocol::PROTOCOL_VERSION);

/// Errors of a translation: the input was malformed. The connection is closed.
pub type Error = vanillite_protocol::Error;
/// Result of a translation.
pub type Result<T> = std::result::Result<T, Error>;

/// The older versions a server or proxy accepts (config `multiversion.versions`).
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Accepted(Vec<Version>);

impl Accepted {
    /// Parses the setting: `all` (every supported version), `none` or empty (off), or a
    /// comma-separated list of version names.
    pub fn parse(setting: &str) -> std::result::Result<Self, String> {
        let setting = setting.trim();
        match setting {
            "" | "none" => return Ok(Self::default()),
            "all" => return Ok(Self(SUPPORTED.to_vec())),
            _ => {}
        }
        let mut out = Vec::new();
        for name in setting.split(',').map(str::trim) {
            let v = SUPPORTED.iter().find(|v| v.id == name).ok_or_else(|| {
                format!(
                    "unsupported version `{name}`; supported: {}",
                    SUPPORTED
                        .iter()
                        .map(|v| v.id)
                        .collect::<Vec<_>>()
                        .join(", ")
                )
            })?;
            if !out.contains(v) {
                out.push(*v);
            }
        }
        Ok(Self(out))
    }

    /// Every supported version.
    pub fn all() -> Self {
        Self(SUPPORTED.to_vec())
    }

    /// Whether no older version is accepted.
    pub fn is_empty(&self) -> bool {
        self.0.is_empty()
    }

    /// The accepted version of a protocol number.
    pub fn version(&self, protocol: i32) -> Option<Version> {
        self.0.iter().copied().find(|v| v.protocol == protocol)
    }

    /// An adapter for a client of `protocol` that starts in `state` (login or configuration),
    /// if that version is accepted.
    pub fn adapter(&self, protocol: i32, state: State) -> Option<Adapter> {
        self.version(protocol).map(|v| Adapter::new(v, state))
    }

    /// The accepted versions.
    pub fn versions(&self) -> &[Version] {
        &self.0
    }
}

/// A status response (`status_response` JSON) for a client of an accepted older `protocol`:
/// the version shown matches the client, so it lists the server as compatible.
pub fn status_json(json: &str, protocol: i32) -> String {
    let current = format!("\"protocol\":{}", vanillite_protocol::PROTOCOL_VERSION);
    json.replacen(&current, &format!("\"protocol\":{protocol}"), 1)
}
