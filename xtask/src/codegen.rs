//! `cargo xtask codegen`: `data/vanilla/` → `crates/vanillite-data/src/generated/`.
//!
//! The output is committed. `--check` regenerates in memory and fails on any difference, so CI
//! notices data and tables that drifted apart.

use std::collections::{BTreeMap, HashMap};
use std::fmt::{Display, Write as _};
use std::path::Path;

use serde_json::Value;

use crate::{Result, read, read_json};

const HEADER: &str = "// @generated by `cargo xtask codegen` from data/vanilla/. Do not edit.\n";

/// Per-state boolean facts, in bit order. `block::flags` is generated from this list.
const FLAGS: &[&str] = &[
    "air",
    "solid",
    "liquid",
    "can_occlude",
    "solid_render",
    "propagates_skylight_down",
    "use_shape_for_light_occlusion",
    "large_collision_shape",
    "random_ticks",
    "replaceable",
    "has_block_entity",
    "signal_source",
    "analog_output",
    "requires_correct_tool",
    "ignited_by_lava",
    "has_offset",
    "redstone_conductor",
    "collision_full_block",
    "collision_offset",
    "outline_offset",
    "interaction_offset",
    "support_offset",
    "visual_offset",
];

/// Shape kinds of a state, in the order of `ShapeSet`.
const SHAPE_KINDS: &[&str] = &[
    "collision",
    "outline",
    "interaction",
    "support",
    "visual",
    "occlusion",
];

pub fn run(root: &Path, check: bool) -> Result<()> {
    let data = root.join("data").join("vanilla");
    let out = root.join("crates/vanillite-data/src/generated");
    let regs = read_json(&data.join("registries.json"))?;
    let files: Vec<(&str, String)> = vec![
        ("mod.rs", module_file()),
        ("version.rs", version(&read(&data.join("version.toml"))?)?),
        ("blocks.rs", blocks(&data, &regs)?),
        ("fluids.rs", fluids(&data, &regs)?),
        ("items.rs", items(&data, &regs)?),
        ("entities.rs", entities(&data)?),
        ("registries.rs", registries(&regs)?),
        (
            "packets.rs",
            packets(&read_json(&data.join("packets.json"))?)?,
        ),
        (
            "dynamic.rs",
            dynamic(&read_json(&data.join("dynamic_registries.json"))?)?,
        ),
    ];
    if check {
        let mut stale = Vec::new();
        for (name, contents) in &files {
            if std::fs::read_to_string(out.join(name)).ok().as_deref() != Some(contents.as_str()) {
                stale.push(*name);
            }
        }
        if !stale.is_empty() {
            return Err(format!(
                "generated tables are not current ({}); run `cargo xtask codegen`",
                stale.join(", ")
            ));
        }
        println!("codegen: generated tables are current");
    } else {
        if out.exists() {
            std::fs::remove_dir_all(&out).map_err(|e| format!("{}: {e}", out.display()))?;
        }
        for (name, contents) in &files {
            crate::write(&out.join(name), contents)?;
        }
        println!("codegen: wrote {}", out.display());
    }
    Ok(())
}

/// A `minecraft:tool` component as a `ToolInfo` literal.
fn tool_info(t: &Value, block_ids: &HashMap<String, usize>) -> Result<String> {
    let mut rules = Vec::new();
    for r in arr(&t["rules"])? {
        let blocks = match &r["blocks"] {
            Value::String(s) if s.starts_with('#') => format!("BlockSet::Tag({:?})", &s[1..]),
            v => {
                let names = match v {
                    Value::String(s) => vec![s.clone()],
                    Value::Array(a) => a
                        .iter()
                        .map(|x| x.as_str().unwrap_or_default().to_owned())
                        .collect(),
                    _ => return Err("tool rule blocks".into()),
                };
                let ids = names
                    .iter()
                    .map(|n| {
                        block_ids
                            .get(n)
                            .copied()
                            .ok_or(format!("unknown block {n}"))
                    })
                    .collect::<Result<Vec<_>>>()?;
                format!("BlockSet::Blocks(&[{}])", join(&ids))
            }
        };
        let speed = match r.get("speed").and_then(Value::as_f64) {
            Some(v) => format!("Some({})", f32_of(&Value::from(v))),
            None => "None".into(),
        };
        let correct = match r.get("correct_for_drops").and_then(Value::as_bool) {
            Some(v) => format!("Some({v})"),
            None => "None".into(),
        };
        rules.push(format!(
            "ToolRule {{ blocks: {blocks}, speed: {speed}, correct_for_drops: {correct} }}"
        ));
    }
    Ok(format!(
        "ToolInfo {{ rules: &[{}], default_mining_speed: {}, damage_per_block: {}, can_destroy_blocks_in_creative: {} }}",
        rules.join(", "),
        f32_of(t.get("default_mining_speed").unwrap_or(&Value::from(1.0))),
        t.get("damage_per_block")
            .and_then(Value::as_u64)
            .unwrap_or(1),
        t.get("can_destroy_blocks_in_creative")
            .and_then(Value::as_bool)
            .unwrap_or(true),
    ))
}

fn module_file() -> String {
    let mut s = String::from(HEADER);
    for m in [
        "blocks",
        "dynamic",
        "entities",
        "fluids",
        "items",
        "packets",
        "registries",
        "version",
    ] {
        let _ = writeln!(s, "pub mod {m};");
    }
    s
}

fn version(toml_src: &str) -> Result<String> {
    let v: toml::Table = toml_src.parse().map_err(|e| format!("version.toml: {e}"))?;
    let s = |k: &str| {
        v.get(k)
            .and_then(toml::Value::as_str)
            .ok_or(format!("version.toml: {k}"))
    };
    let i = |k: &str| {
        v.get(k)
            .and_then(toml::Value::as_integer)
            .ok_or(format!("version.toml: {k}"))
    };
    let pair = |k: &str| -> Result<(i64, i64)> {
        let a = v
            .get(k)
            .and_then(toml::Value::as_array)
            .ok_or(format!("version.toml: {k}"))?;
        let n = |x: Option<&toml::Value>| x.and_then(toml::Value::as_integer).unwrap_or(0);
        Ok((n(a.first()), n(a.get(1))))
    };
    let rp = pair("resource_pack_version")?;
    let dp = pair("data_pack_version")?;
    let mut o = String::from(HEADER);
    let _ = write!(
        o,
        "\n/// Minecraft version id (also the version of the `minecraft:core` known pack).\n\
         pub const VERSION_ID: &str = {:?};\n\
         /// Protocol version.\n\
         pub const PROTOCOL_VERSION: i32 = {};\n\
         /// Data version of worlds and NBT data.\n\
         pub const DATA_VERSION: i32 = {};\n\
         /// Resource pack format (major, minor).\n\
         pub const RESOURCE_PACK_VERSION: (u32, u32) = ({}, {});\n\
         /// Data pack format (major, minor).\n\
         pub const DATA_PACK_VERSION: (u32, u32) = ({}, {});\n\
         /// Java version the server jar needs (datagen, extractor, goldens).\n\
         pub const JAVA_VERSION: u32 = {};\n\
         /// Pinned download of Mojang's server jar.\n\
         pub const SERVER_JAR_URL: &str = {:?};\n\
         /// SHA-1 of the pinned server jar.\n\
         pub const SERVER_JAR_SHA1: &str = {:?};\n",
        s("id")?,
        i("protocol")?,
        i("data_version")?,
        rp.0,
        rp.1,
        dp.0,
        dp.1,
        i("java_version")?,
        s("server_jar_url")?,
        s("server_jar_sha1")?,
    );
    Ok(o)
}

fn blocks(data: &Path, regs: &Value) -> Result<String> {
    let blocks = arr(&read_json(&data.join("blocks.json"))?)?;
    let states = arr(&read_json(&data.join("block_states.json"))?)?;
    let shapes = arr(&read_json(&data.join("shapes.json"))?)?;
    let item_ids = ids(regs, "minecraft:item")?;
    let be_ids = ids(regs, "minecraft:block_entity_type")?;
    let sound_ids = ids(regs, "minecraft:sound_event")?;
    let mut sound_types: Vec<String> = Vec::new();

    let mut props: Vec<(String, Vec<String>)> = Vec::new();
    let mut prop_index: HashMap<(String, Vec<String>), usize> = HashMap::new();
    let mut infos = String::new();
    let mut block_facts = Vec::new();
    let mut state_block = Vec::new();
    for (id, b) in blocks.iter().enumerate() {
        let name = b["name"].as_str().ok_or("block name")?;
        let mut pidx = Vec::new();
        for p in arr(&b["properties"])? {
            let key = (
                p["name"].as_str().ok_or("property name")?.to_owned(),
                arr(&p["values"])?
                    .iter()
                    .map(|v| v.as_str().unwrap_or_default().to_owned())
                    .collect::<Vec<_>>(),
            );
            let next = props.len();
            let i = *prop_index.entry(key.clone()).or_insert_with(|| {
                props.push(key);
                next
            });
            pidx.push(i);
        }
        let opt_id = |key: &str, table: &HashMap<String, usize>| -> Result<String> {
            match b.get(key).and_then(Value::as_str) {
                None => Ok("u16::MAX".into()),
                Some(n) => table
                    .get(n)
                    .map(ToString::to_string)
                    .ok_or_else(|| format!("{name}: unknown {key} {n}")),
            }
        };
        let count = num(&b["state_count"])?;
        let _ = writeln!(
            infos,
            "    BlockInfo {{ name: {name:?}, first_state: {}, state_count: {count}, default_state: {}, \
             properties: &[{}], hardness: {}, blast_resistance: {}, friction: {}, speed_factor: {}, \
             jump_factor: {}, max_horizontal_offset: {}, max_vertical_offset: {}, dynamic_shape: {}, \
             item: {}, block_entity: {}, kind: BlockKind::{}, sound: {} }},",
            num(&b["first_state"])?,
            num(&b["default_state"])?,
            join(&pidx),
            f32_of(&b["hardness"]),
            f32_of(&b["blast_resistance"]),
            f32_of(&b["friction"]),
            f32_of(&b["speed_factor"]),
            f32_of(&b["jump_factor"]),
            f32_of(&b["max_horizontal_offset"]),
            f32_of(&b["max_vertical_offset"]),
            b["dynamic_shape"].as_bool().unwrap_or(false),
            opt_id("item", &item_ids)?,
            opt_id("block_entity", &be_ids)?,
            camel(kind_of(b)),
            {
                let st = sound_type(&b["sound"], &sound_ids)?;
                match sound_types.iter().position(|x| *x == st) {
                    Some(i) => i,
                    None => {
                        sound_types.push(st);
                        sound_types.len() - 1
                    }
                }
            },
        );
        let facts = b["facts"].as_object().ok_or("block facts")?.clone();
        for _ in 0..count {
            state_block.push(id);
            block_facts.push(facts.clone());
        }
    }
    for diff in &states {
        let id = usize::try_from(num(&diff["id"])?).map_err(|e| e.to_string())?;
        let facts = block_facts
            .get_mut(id)
            .ok_or_else(|| format!("block_states.json: state {id} out of range"))?;
        for (k, v) in diff.as_object().ok_or("state")? {
            if k != "id" {
                facts.insert(k.clone(), v.clone());
            }
        }
    }
    let state_count = block_facts.len();

    let mut flags = Vec::with_capacity(state_count);
    let mut light = Vec::with_capacity(state_count);
    let mut fluid = Vec::with_capacity(state_count);
    let mut shape_sets: Vec<[u64; 6]> = Vec::new();
    let mut shape_set_index: HashMap<[u64; 6], usize> = HashMap::new();
    let mut state_shapes = Vec::with_capacity(state_count);
    let mut instruments: Vec<String> = Vec::new();
    let mut push_reactions: Vec<String> = Vec::new();
    let mut misc: Vec<String> = Vec::new();
    let mut misc_index: HashMap<String, usize> = HashMap::new();
    let mut state_misc = Vec::with_capacity(state_count);
    for (i, facts) in block_facts.iter().enumerate() {
        let f = |k: &str| facts.get(k).and_then(Value::as_bool).unwrap_or(false);
        let mut bits = 0u32;
        for (bit, name) in FLAGS.iter().enumerate() {
            if f(name) {
                bits |= 1 << bit;
            }
        }
        flags.push(bits);
        let emission = num(&facts["light_emission"])?;
        let dampening = num(&facts["light_dampening"])?;
        if emission > 15 || dampening > 15 {
            return Err(format!("state {i}: light values out of range"));
        }
        light.push(emission << 4 | dampening);
        let fl = num(&facts["fluid_state"])?;
        if fl > 255 {
            return Err(format!("state {i}: fluid state id {fl} does not fit u8"));
        }
        fluid.push(fl);

        let mut set = [0u64; 6];
        for (slot, kind) in set.iter_mut().zip(SHAPE_KINDS) {
            *slot = facts[*kind]
                .as_u64()
                .ok_or_else(|| format!("state {i}: no {kind} shape (extractor failed)"))?;
        }
        let next = shape_sets.len();
        let si = *shape_set_index.entry(set).or_insert_with(|| {
            shape_sets.push(set);
            next
        });
        state_shapes.push(si);

        let instrument = facts["instrument"].as_str().unwrap_or("harp").to_owned();
        let ii = match instruments.iter().position(|x| *x == instrument) {
            Some(p) => p,
            None => {
                instruments.push(instrument);
                instruments.len() - 1
            }
        };
        let pr = facts["push_reaction"]
            .as_str()
            .ok_or("push_reaction")?
            .to_owned();
        if !push_reactions.contains(&pr) {
            push_reactions.push(pr);
        }
        let hardness = blocks[state_block[i]]["hardness"].clone();
        let m = format!(
            "StateMisc {{ destroy_speed: {}, map_color: {}, push_reaction: PushReaction::{}, \
             instrument: {ii}, sturdy_full: {}, sturdy_center: {}, sturdy_rigid: {} }}",
            f32_of(facts.get("destroy_speed").unwrap_or(&hardness)),
            facts.get("map_color").and_then(Value::as_u64).unwrap_or(0),
            camel(facts["push_reaction"].as_str().unwrap_or_default()),
            num(&facts["sturdy_full"])?,
            num(&facts["sturdy_center"])?,
            num(&facts["sturdy_rigid"])?,
        );
        let next = misc.len();
        let mi = *misc_index.entry(m.clone()).or_insert_with(|| {
            misc.push(m);
            next
        });
        state_misc.push(mi);
    }
    for (what, v) in [("shape sets", shape_sets.len()), ("misc", misc.len())] {
        if v > usize::from(u16::MAX) {
            return Err(format!("too many distinct {what} for u16"));
        }
    }

    let mut o = String::from(HEADER);
    o.push_str("\nuse crate::block::{BlockId, BlockInfo, PropertyInfo, SoundType, StateMisc};\n\n");
    let mut kinds: Vec<String> = blocks.iter().map(|b| kind_of(b).to_owned()).collect();
    kinds.sort();
    kinds.dedup();
    enum_def(
        &mut o,
        "The Java class of a block (`StairBlock`, `SlabBlock`, …).",
        "BlockKind",
        &kinds,
    );
    let _ = writeln!(
        o,
        "/// Distinct block sound types (`SoundType`) with sound event ids.\npub static SOUND_TYPES: [SoundType; {}] = [",
        sound_types.len()
    );
    for t in &sound_types {
        let _ = writeln!(o, "    {t},");
    }
    o.push_str("];\n\n");
    push_reactions.sort();
    enum_def(
        &mut o,
        "How a block state reacts to pistons.",
        "PushReaction",
        &push_reactions,
    );
    let _ = writeln!(
        o,
        "/// Number of blocks.\npub const BLOCK_COUNT: usize = {};",
        blocks.len()
    );
    let _ = writeln!(
        o,
        "/// Number of block states (global state ids are `0..STATE_COUNT`).\npub const STATE_COUNT: usize = {state_count};"
    );
    o.push_str("\n/// Per-state boolean facts, as bits of `STATE_FLAGS`.\npub mod flags {\n");
    for (bit, name) in FLAGS.iter().enumerate() {
        let _ = writeln!(
            o,
            "    pub const {}: u32 = 1 << {bit};",
            name.to_uppercase()
        );
    }
    o.push_str("}\n\n/// Distinct block state properties (name and values in Vanilla's order).\n");
    let _ = writeln!(
        o,
        "pub static PROPERTIES: [PropertyInfo; {}] = [",
        props.len()
    );
    for (name, values) in &props {
        let _ = writeln!(
            o,
            "    PropertyInfo {{ name: {name:?}, values: &[{}] }},",
            values
                .iter()
                .map(|v| format!("{v:?}"))
                .collect::<Vec<_>>()
                .join(", ")
        );
    }
    let _ = writeln!(
        o,
        "];\n\n/// Blocks by id.\npub static BLOCKS: [BlockInfo; {}] = [",
        blocks.len()
    );
    o.push_str(&infos);
    o.push_str("];\n\n");
    table(
        &mut o,
        "Block of each state.",
        "STATE_BLOCK",
        "u16",
        &state_block,
    );
    table(
        &mut o,
        "`flags` bits of each state.",
        "STATE_FLAGS",
        "u32",
        &flags,
    );
    table(
        &mut o,
        "Light of each state: emission in the high nibble, dampening in the low nibble.",
        "STATE_LIGHT",
        "u8",
        &light,
    );
    table(
        &mut o,
        "Fluid state id of each state.",
        "STATE_FLUID",
        "u8",
        &fluid,
    );
    table(
        &mut o,
        "Index into `SHAPE_SETS` of each state.",
        "STATE_SHAPES",
        "u16",
        &state_shapes,
    );
    let _ = writeln!(
        o,
        "/// Shape ids (into `SHAPES`): collision, outline, interaction, support, visual, occlusion.\n\
         pub static SHAPE_SETS: [[u16; 6]; {}] = [",
        shape_sets.len()
    );
    for chunk in shape_sets.chunks(6) {
        let row: Vec<String> = chunk.iter().map(|s| format!("[{}]", join(s))).collect();
        let _ = writeln!(o, "    {},", row.join(", "));
    }
    o.push_str("];\n\n");
    table(
        &mut o,
        "Index into `MISC` of each state.",
        "STATE_MISC",
        "u16",
        &state_misc,
    );
    let _ = writeln!(
        o,
        "/// Distinct rarely used per-state facts.\npub static MISC: [StateMisc; {}] = [",
        misc.len()
    );
    for m in &misc {
        let _ = writeln!(o, "    {m},");
    }
    let _ = writeln!(
        o,
        "];\n\n/// Note block instruments, indexed by `StateMisc::instrument`.\npub static INSTRUMENTS: [&str; {}] = [{}];\n",
        instruments.len(),
        instruments
            .iter()
            .map(|v| format!("{v:?}"))
            .collect::<Vec<_>>()
            .join(", ")
    );
    let _ = writeln!(
        o,
        "/// Shapes as boxes `[min_x, min_y, min_z, max_x, max_y, max_z]` in block coordinates.\n\
         /// Shape 0 is empty, shape 1 is the full block.\n\
         pub static SHAPES: [&[[f64; 6]]; {}] = [",
        shapes.len()
    );
    for s in &shapes {
        let boxes: Vec<String> = arr(s)?
            .iter()
            .map(|b| {
                let c: Vec<String> = b
                    .as_array()
                    .map(|a| a.iter().map(f64_of).collect())
                    .unwrap_or_default();
                format!("[{}]", c.join(", "))
            })
            .collect();
        let _ = writeln!(o, "    &[{}],", boxes.join(", "));
    }
    o.push_str("];\n\n/// Block ids by name.\npub mod ids {\n    use super::BlockId;\n");
    for (id, b) in blocks.iter().enumerate() {
        let _ = writeln!(
            o,
            "    pub const {}: BlockId = BlockId({id});",
            const_name(b["name"].as_str().unwrap_or_default())
        );
    }
    o.push_str("}\n");
    Ok(o)
}

/// A block's `SoundType` as a literal with sound event ids.
fn sound_type(s: &Value, sound_ids: &HashMap<String, usize>) -> Result<String> {
    let id = |k: &str| -> Result<usize> {
        let n = s[k].as_str().ok_or_else(|| format!("sound {k}"))?;
        sound_ids
            .get(n)
            .copied()
            .ok_or_else(|| format!("unknown sound event {n}"))
    };
    Ok(format!(
        "SoundType {{ volume: {}, pitch: {}, break_sound: {}, step_sound: {}, place_sound: {}, hit_sound: {}, fall_sound: {} }}",
        f32_of(&s["volume"]),
        f32_of(&s["pitch"]),
        id("break")?,
        id("step")?,
        id("place")?,
        id("hit")?,
        id("fall")?,
    ))
}

/// The Java class of a block (`StairBlock`).
fn kind_of(b: &Value) -> &str {
    b["class"].as_str().unwrap_or("Block")
}

/// Emits a field-less enum whose variants are Vanilla's (snake case) names in CamelCase.
fn enum_def(o: &mut String, doc: &str, name: &str, values: &[String]) {
    let _ = writeln!(
        o,
        "/// {doc}\n#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]\npub enum {name} {{"
    );
    for v in values {
        let _ = writeln!(o, "    {},", camel(v));
    }
    o.push_str("}\n\n");
}

/// `push_pull` → `PushPull`.
fn camel(s: &str) -> String {
    s.split('_')
        .map(|w| {
            let mut c = w.chars();
            c.next()
                .map(|f| f.to_ascii_uppercase().to_string() + c.as_str())
                .unwrap_or_default()
        })
        .collect()
}

fn fluids(data: &Path, regs: &Value) -> Result<String> {
    let fluid_ids = ids(regs, "minecraft:fluid")?;
    let states = arr(&read_json(&data.join("fluid_states.json"))?)?;
    let mut o = String::from(HEADER);
    o.push_str("\nuse crate::fluid::FluidStateInfo;\n\n");
    let _ = writeln!(
        o,
        "/// Fluid states by global fluid state id.\npub static FLUID_STATES: [FluidStateInfo; {}] = [",
        states.len()
    );
    for s in &states {
        let fluid = s["fluid"].as_str().unwrap_or_default();
        let _ = writeln!(
            o,
            "    FluidStateInfo {{ fluid: {}, amount: {}, source: {}, falling: {}, own_height: {}, \
             random_ticks: {}, explosion_resistance: {}, block_state: {} }},",
            fluid_ids
                .get(fluid)
                .ok_or_else(|| format!("unknown fluid {fluid}"))?,
            num(&s["amount"])?,
            s["source"].as_bool().unwrap_or(false),
            s["properties"]["falling"] == "true",
            f32_of(&s["own_height"]),
            s["random_ticks"].as_bool().unwrap_or(false),
            f32_of(&s["explosion_resistance"]),
            num(&s["block_state"])?,
        );
    }
    o.push_str("];\n");
    Ok(o)
}

fn items(data: &Path, regs: &Value) -> Result<String> {
    let block_ids = ids(regs, "minecraft:block")?;
    let items = arr(&read_json(&data.join("items.json"))?)?;
    let mut o = String::from(HEADER);
    o.push_str("\nuse crate::item::{BlockSet, ItemId, ItemInfo, ToolInfo, ToolRule};\n\n");
    let mut rarities: Vec<String> = items
        .iter()
        .map(|i| {
            i["components"]["minecraft:rarity"]
                .as_str()
                .unwrap_or("common")
                .to_owned()
        })
        .collect();
    rarities.sort();
    rarities.dedup();
    enum_def(
        &mut o,
        "Item rarity (`minecraft:rarity` component).",
        "Rarity",
        &rarities,
    );
    let _ = writeln!(
        o,
        "/// Items by id, with the default values of their core components.\npub static ITEMS: [ItemInfo; {}] = [",
        items.len()
    );
    let mut tools: Vec<String> = Vec::new();
    let mut item_lines = String::new();
    for it in &items {
        let name = it["name"].as_str().unwrap_or_default();
        let c = &it["components"];
        let rarity = camel(c["minecraft:rarity"].as_str().unwrap_or("common"));
        let tool = match c.get("minecraft:tool") {
            None => "u16::MAX".to_owned(),
            Some(t) => {
                let t = tool_info(t, &block_ids).map_err(|e| format!("{name}: {e}"))?;
                let i = match tools.iter().position(|x| *x == t) {
                    Some(i) => i,
                    None => {
                        tools.push(t);
                        tools.len() - 1
                    }
                };
                i.to_string()
            }
        };
        let block = match it.get("block").and_then(Value::as_str) {
            None => "u16::MAX".to_owned(),
            Some(b) => block_ids
                .get(b)
                .ok_or_else(|| format!("{name}: unknown block {b}"))?
                .to_string(),
        };
        // `EquipmentSlot` ordinal of the `minecraft:equippable` slot, 255 without the component.
        let equip = match c["minecraft:equippable"]["slot"].as_str() {
            None => 255,
            Some(slot) => [
                "mainhand", "offhand", "feet", "legs", "chest", "head", "body", "saddle",
            ]
            .iter()
            .position(|s| *s == slot)
            .ok_or_else(|| format!("{name}: unknown equipment slot {slot}"))?,
        };
        let _ = writeln!(
            item_lines,
            "    ItemInfo {{ name: {name:?}, max_stack_size: {}, max_damage: {}, rarity: Rarity::{rarity}, block: {block}, tool: {tool}, equip_slot: {equip} }},",
            c["minecraft:max_stack_size"].as_u64().unwrap_or(1),
            c["minecraft:max_damage"].as_u64().unwrap_or(0),
        );
    }
    o.push_str(&item_lines);
    let _ = writeln!(
        o,
        "];\n\n/// Distinct default `minecraft:tool` components.\npub static TOOLS: [ToolInfo; {}] = [",
        tools.len()
    );
    for t in &tools {
        let _ = writeln!(o, "    {t},");
    }
    o.push_str("];\n\n/// Item ids by name.\npub mod ids {\n    use super::ItemId;\n");
    for (id, it) in items.iter().enumerate() {
        let _ = writeln!(
            o,
            "    pub const {}: ItemId = ItemId({id});",
            const_name(it["name"].as_str().unwrap_or_default())
        );
    }
    o.push_str("}\n");
    Ok(o)
}

fn entities(data: &Path) -> Result<String> {
    let types = arr(&read_json(&data.join("entities.json"))?)?;
    let attrs = arr(&read_json(&data.join("attributes.json"))?)?;
    let attr_ids: HashMap<&str, usize> = attrs
        .iter()
        .enumerate()
        .map(|(i, a)| (a["name"].as_str().unwrap_or_default(), i))
        .collect();
    let mut o = String::from(HEADER);
    o.push_str("\nuse crate::entity::{AttributeInfo, EntityTypeId, EntityTypeInfo};\n\n");
    let _ = writeln!(
        o,
        "/// Attributes by id.\npub static ATTRIBUTES: [AttributeInfo; {}] = [",
        attrs.len()
    );
    for a in &attrs {
        let _ = writeln!(
            o,
            "    AttributeInfo {{ name: {:?}, default: {}, syncable: {} }},",
            a["name"].as_str().unwrap_or_default(),
            f64_of(&a["default"]),
            a["syncable"].as_bool().unwrap_or(false)
        );
    }
    let _ = writeln!(
        o,
        "];\n\n/// Entity types by id.\npub static ENTITY_TYPES: [EntityTypeInfo; {}] = [",
        types.len()
    );
    for t in &types {
        let mut base = Vec::new();
        if let Some(m) = t["attributes"].as_object() {
            for (k, v) in m {
                let id = attr_ids
                    .get(k.as_str())
                    .ok_or_else(|| format!("unknown attribute {k}"))?;
                base.push(format!("({id}, {})", f64_of(v)));
            }
        }
        let _ = writeln!(
            o,
            "    EntityTypeInfo {{ name: {:?}, category: {:?}, width: {}, height: {}, eye_height: {}, \
             fixed_size: {}, fire_immune: {}, summonable: {}, can_spawn_far_from_player: {}, \
             tracking_range: {}, update_interval: {}, track_deltas: {}, attributes: &[{}] }},",
            t["name"].as_str().unwrap_or_default(),
            t["category"].as_str().unwrap_or_default(),
            f32_of(&t["width"]),
            f32_of(&t["height"]),
            f32_of(&t["eye_height"]),
            t["fixed_size"].as_bool().unwrap_or(false),
            t["fire_immune"].as_bool().unwrap_or(false),
            t["summonable"].as_bool().unwrap_or(false),
            t["can_spawn_far_from_player"].as_bool().unwrap_or(false),
            num(&t["tracking_range"])?,
            t["update_interval"].as_i64().ok_or("update_interval")?,
            t["track_deltas"].as_bool().unwrap_or(false),
            base.join(", ")
        );
    }
    o.push_str("];\n\n/// Entity type ids by name.\npub mod ids {\n    use super::EntityTypeId;\n");
    for (id, t) in types.iter().enumerate() {
        let _ = writeln!(
            o,
            "    pub const {}: EntityTypeId = EntityTypeId({id});",
            const_name(t["name"].as_str().unwrap_or_default())
        );
    }
    o.push_str("}\n");
    Ok(o)
}

fn registries(regs: &Value) -> Result<String> {
    let regs = regs.as_object().ok_or("registries.json")?;
    let mut o = String::from(HEADER);
    o.push_str("\nuse crate::registry::Registry;\n");
    let mut names = Vec::new();
    for (name, r) in regs {
        let list = arr(&r["entries"])?;
        let entries: Vec<&str> = list
            .iter()
            .map(|e| e.as_str().unwrap_or_default())
            .collect();
        if entries.len() > usize::from(u16::MAX) {
            return Err(format!("{name}: too many entries for a u16 index"));
        }
        let mut sorted: Vec<usize> = (0..entries.len()).collect();
        sorted.sort_by_key(|i| entries[*i]);
        let ident = const_name(name);
        let default = match r.get("default").and_then(Value::as_str) {
            Some(d) => format!("Some({d:?})"),
            None => "None".into(),
        };
        let _ = writeln!(
            o,
            "\n/// `{name}`.\npub static {ident}: Registry = Registry {{\n    name: {name:?},\n    \
             protocol_id: {},\n    default: {default},\n    entries: &[",
            num(&r["protocol_id"])?
        );
        for line in entries.chunks(4) {
            let l: Vec<String> = line.iter().map(|e| format!("{e:?}")).collect();
            let _ = writeln!(o, "        {},", l.join(", "));
        }
        o.push_str("    ],\n    sorted: &[\n");
        numbers(&mut o, &sorted, "        ");
        o.push_str("    ],\n};\n");
        names.push(ident);
    }
    let _ = writeln!(
        o,
        "\n/// All static registries, sorted by name.\npub static ALL: [&Registry; {}] = [",
        names.len()
    );
    for n in &names {
        let _ = writeln!(o, "    &{n},");
    }
    o.push_str("];\n");
    Ok(o)
}

fn packets(p: &Value) -> Result<String> {
    let mut o = String::from(HEADER);
    for (state, dirs) in p.as_object().ok_or("packets.json")? {
        let _ = writeln!(
            o,
            "\n/// Packet ids of the `{state}` state.\npub mod {state} {{"
        );
        for (dir, list) in dirs.as_object().ok_or("packets.json")? {
            let list = arr(list)?;
            let _ = writeln!(o, "    /// {dir} packets.\n    pub mod {dir} {{");
            for (id, name) in list.iter().enumerate() {
                let _ = writeln!(
                    o,
                    "        pub const {}: i32 = {id};",
                    const_name(name.as_str().unwrap_or_default())
                );
            }
            let _ = writeln!(
                o,
                "        /// Packet names by id.\n        pub static NAMES: [&str; {}] = [",
                list.len()
            );
            for name in &list {
                let _ = writeln!(o, "            {:?},", name.as_str().unwrap_or_default());
            }
            o.push_str("        ];\n    }\n");
        }
        o.push_str("}\n");
    }
    Ok(o)
}

fn dynamic(d: &Value) -> Result<String> {
    let mut o = String::from(HEADER);
    let docs: BTreeMap<&str, &str> = BTreeMap::from([
        (
            "world",
            "Data-driven registries of a world, in Vanilla's load order.",
        ),
        (
            "dimension",
            "Dimension registries, loaded after the world registries.",
        ),
        ("reloadable", "Registries reloaded by `/reload`."),
        (
            "synchronized",
            "Registries sent to the client in the configuration phase, in Vanilla's order.",
        ),
    ]);
    for (key, doc) in docs {
        let list = arr(&d[key])?;
        let _ = writeln!(
            o,
            "\n/// {doc}\npub static {}: [&str; {}] = [",
            key.to_uppercase(),
            list.len()
        );
        for n in &list {
            let _ = writeln!(o, "    {:?},", n.as_str().unwrap_or_default());
        }
        o.push_str("];\n");
    }
    Ok(o)
}

// ---------------------------------------------------------------------------------------------
// Helpers

fn arr(v: &Value) -> Result<Vec<Value>> {
    v.as_array()
        .cloned()
        .ok_or_else(|| "expected a JSON array".into())
}

fn num(v: &Value) -> Result<u64> {
    v.as_u64()
        .ok_or_else(|| format!("expected an unsigned number, got {v}"))
}

/// Registry entry name → protocol id.
fn ids(regs: &Value, registry: &str) -> Result<HashMap<String, usize>> {
    Ok(arr(&regs[registry]["entries"])?
        .iter()
        .enumerate()
        .map(|(i, e)| (e.as_str().unwrap_or_default().to_owned(), i))
        .collect())
}

/// Shortest literal that reads back as the same `f32` (Java floats are written that way).
fn f32_of(v: &Value) -> String {
    #[expect(clippy::cast_possible_truncation, reason = "the value is a Java float")]
    let f = v.as_f64().unwrap_or(0.0) as f32;
    format!("{f:?}")
}

fn f64_of(v: &Value) -> String {
    format!("{:?}", v.as_f64().unwrap_or(0.0))
}

fn join<T: Display>(v: &[T]) -> String {
    v.iter()
        .map(ToString::to_string)
        .collect::<Vec<_>>()
        .join(", ")
}

/// `minecraft:worldgen/biome` → `WORLDGEN_BIOME`; a leading digit gets a `_` prefix.
fn const_name(name: &str) -> String {
    let path = name.strip_prefix("minecraft:").unwrap_or(name);
    let mut s: String = path
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_uppercase()
            } else {
                '_'
            }
        })
        .collect();
    if s.starts_with(|c: char| c.is_ascii_digit()) {
        s.insert(0, '_');
    }
    s
}

fn table<T: Display>(o: &mut String, doc: &str, name: &str, ty: &str, values: &[T]) {
    let _ = writeln!(
        o,
        "/// {doc}\npub static {name}: [{ty}; {}] = [",
        values.len()
    );
    numbers(o, values, "    ");
    o.push_str("];\n\n");
}

/// Numbers packed into lines of at most 100 columns.
fn numbers<T: Display>(o: &mut String, values: &[T], indent: &str) {
    let mut line = String::from(indent);
    for v in values {
        let item = format!("{v},");
        if line.len() + item.len() + 1 > 100 && line.len() > indent.len() {
            o.push_str(line.trim_end());
            o.push('\n');
            line = String::from(indent);
        }
        line.push_str(&item);
        line.push(' ');
    }
    if line.len() > indent.len() {
        o.push_str(line.trim_end());
        o.push('\n');
    }
}
