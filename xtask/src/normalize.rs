//! Turns datagen reports and extractor output into the committed, diffable `data/vanilla/`.
//!
//! Large tables are JSON arrays with one entry per line, so a version update gives a
//! reviewable diff. `block_states.json` lists only the states whose facts differ from their
//! block's default state, and only the differing facts.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

use serde_json::{Map, Value, json};

use crate::{Result, read_json, write};

/// Version facts from the inner jar's `version.json` plus the pinned download.
pub struct VersionInfo {
    id: String,
    protocol: u64,
    data_version: u64,
    resource_pack: [u64; 2],
    data_pack: [u64; 2],
    java_version: u64,
    jar_url: String,
    jar_sha1: String,
}

impl VersionInfo {
    pub fn new(v: &Value, jar_url: String, jar_sha1: String) -> Result<Self> {
        let num = |k: &[&str]| {
            k.iter()
                .fold(v, |v, k| &v[*k])
                .as_u64()
                .ok_or_else(|| format!("version.json: missing {}", k.join(".")))
        };
        Ok(Self {
            id: v["id"]
                .as_str()
                .ok_or("version.json: missing id")?
                .to_owned(),
            protocol: num(&["protocol_version"])?,
            data_version: num(&["world_version"])?,
            resource_pack: [
                num(&["pack_version", "resource_major"])?,
                num(&["pack_version", "resource_minor"])?,
            ],
            data_pack: [
                num(&["pack_version", "data_major"])?,
                num(&["pack_version", "data_minor"])?,
            ],
            java_version: num(&["java_version"])?,
            jar_url,
            jar_sha1,
        })
    }

    fn to_toml(&self) -> String {
        format!(
            "# Generated by `cargo xtask vanilla update`. Do not edit.\n\
             id = \"{}\"\n\
             protocol = {}\n\
             data_version = {}\n\
             resource_pack_version = [{}, {}]\n\
             data_pack_version = [{}, {}]\n\
             java_version = {}\n\
             server_jar_url = \"{}\"\n\
             server_jar_sha1 = \"{}\"\n",
            self.id,
            self.protocol,
            self.data_version,
            self.resource_pack[0],
            self.resource_pack[1],
            self.data_pack[0],
            self.data_pack[1],
            self.java_version,
            self.jar_url,
            self.jar_sha1
        )
    }
}

pub fn run(reports: &Path, extracted: &Path, info: &VersionInfo, out: &Path) -> Result<()> {
    if out.exists() {
        std::fs::remove_dir_all(out).map_err(|e| format!("{}: {e}", out.display()))?;
    }
    write(&out.join("version.toml"), &info.to_toml())?;

    let registries = registries(&read_json(&reports.join("registries.json"))?)?;
    blocks(
        &read_json(&reports.join("blocks.json"))?,
        &read_json(&extracted.join("blocks.json"))?,
        &registries,
        out,
    )?;
    items(
        reports,
        &read_json(&extracted.join("items.json"))?,
        &registries,
        out,
    )?;
    entities(&read_json(&extracted.join("entities.json"))?, out)?;
    write(
        &out.join("fluid_states.json"),
        &lines(&as_array(&read_json(
            &extracted.join("fluid_states.json"),
        )?)?),
    )?;
    write(&out.join("registries.json"), &pretty(&registries))?;
    write(
        &out.join("packets.json"),
        &pretty(&packets(&read_json(&reports.join("packets.json"))?)?),
    )?;
    write(
        &out.join("dynamic_registries.json"),
        &pretty(&read_json(&extracted.join("registries.json"))?),
    )?;
    write(
        &out.join("commands.json"),
        &pretty(&read_json(&reports.join("commands.json"))?),
    )?;
    for dim in ["overworld", "nether"] {
        let src = reports.join(format!("biome_parameters/minecraft/{dim}.json"));
        write(
            &out.join(format!("biome_parameters/{dim}.json")),
            &lines(&as_array(&read_json(&src)?["biomes"])?),
        )?;
    }
    Ok(())
}

/// `{registry: {protocol_id, default?, entries: [names in protocol id order]}}`.
fn registries(report: &Value) -> Result<Value> {
    let mut out = Map::new();
    for (name, reg) in obj(report)? {
        let mut entries: Vec<(u64, &str)> = obj(&reg["entries"])?
            .iter()
            .map(|(k, v)| (v["protocol_id"].as_u64().unwrap_or(u64::MAX), k.as_str()))
            .collect();
        entries.sort_unstable();
        dense(name, entries.iter().map(|e| e.0))?;
        let mut r = Map::new();
        r.insert("protocol_id".into(), reg["protocol_id"].clone());
        if let Some(d) = reg.get("default") {
            r.insert("default".into(), d.clone());
        }
        r.insert(
            "entries".into(),
            entries.iter().map(|e| Value::from(e.1)).collect(),
        );
        out.insert(name.clone(), Value::Object(r));
    }
    Ok(Value::Object(out))
}

/// `{state: {direction: [names in id order]}}`.
fn packets(report: &Value) -> Result<Value> {
    let mut out = Map::new();
    for (state, dirs) in obj(report)? {
        let mut d = Map::new();
        for (dir, packets) in obj(dirs)? {
            let mut list: Vec<(u64, &str)> = obj(packets)?
                .iter()
                .map(|(k, v)| (v["protocol_id"].as_u64().unwrap_or(u64::MAX), k.as_str()))
                .collect();
            list.sort_unstable();
            dense(&format!("{state}/{dir}"), list.iter().map(|e| e.0))?;
            d.insert(dir.clone(), list.iter().map(|e| Value::from(e.1)).collect());
        }
        out.insert(state.clone(), Value::Object(d));
    }
    Ok(Value::Object(out))
}

fn blocks(report: &Value, extracted: &Value, registries: &Value, out: &Path) -> Result<()> {
    let report = obj(report)?;
    let names = as_array(&registries["minecraft:block"]["entries"])?;
    let ext_blocks = as_array(&extracted["blocks"])?;
    if names.len() != ext_blocks.len() || names.len() != report.len() {
        return Err("block counts of registry, report and extractor differ".into());
    }
    let mut block_lines = Vec::new();
    let mut state_lines = Vec::new();
    let mut next_state = 0u64;
    for (id, (name, ext)) in names.iter().zip(&ext_blocks).enumerate() {
        let name = name.as_str().ok_or("block name")?;
        if ext["name"] != name {
            return Err(format!(
                "extractor block {id} is {}, expected {name}",
                ext["name"]
            ));
        }
        let rep = report
            .get(name)
            .ok_or_else(|| format!("{name} not in blocks.json"))?;
        let states = as_array(&ext["states"])?;
        let rep_states = as_array(&rep["states"])?;
        if states.len() != rep_states.len() {
            return Err(format!("{name}: state counts differ"));
        }

        // Vanilla's state definition orders properties by name; the last varies fastest. Values
        // keep their report order. The check below proves that state ids follow this layout.
        let mut props = Vec::new();
        if let Some(p) = rep.get("properties") {
            for (pname, values) in obj(p)? {
                props.push((pname.as_str(), as_array(values)?));
            }
        }
        props.sort_by_key(|p| p.0);
        let first = states[0]["id"].as_u64().ok_or("state id")?;
        if first != next_state {
            return Err(format!(
                "{name}: first state {first}, expected {next_state}"
            ));
        }
        let mut default_state = None;
        for rs in &rep_states {
            let id = rs["id"].as_u64().ok_or("state id")?;
            let mut index = 0u64;
            for (pname, values) in &props {
                let v = &rs["properties"][*pname];
                let vi = values.iter().position(|x| x == v).ok_or("property value")?;
                index = index * values.len() as u64 + vi as u64;
            }
            if first + index != id {
                return Err(format!(
                    "{name}: state {id} does not follow the property stride order"
                ));
            }
            if rs.get("default").and_then(Value::as_bool) == Some(true) {
                default_state = Some(id);
            }
        }
        let default_state = default_state.ok_or_else(|| format!("{name}: no default state"))?;
        let default_facts =
            facts(&states[usize::try_from(default_state - first).map_err(|e| e.to_string())?]);

        let mut b = Map::new();
        b.insert("name".into(), name.into());
        b.insert("id".into(), id.into());
        b.insert("first_state".into(), first.into());
        b.insert("state_count".into(), states.len().into());
        b.insert("default_state".into(), default_state.into());
        b.insert(
            "properties".into(),
            props
                .iter()
                .map(|(n, v)| json!({"name": n, "values": v}))
                .collect(),
        );
        for (k, v) in obj(ext)? {
            if k != "name" && k != "states" {
                b.insert(k.clone(), v.clone());
            }
        }
        b.insert("facts".into(), Value::Object(default_facts.clone()));
        block_lines.push(Value::Object(b));

        for s in &states {
            let mut line = Map::new();
            line.insert("id".into(), s["id"].clone());
            for (k, v) in facts(s) {
                if default_facts.get(&k) != Some(&v) {
                    line.insert(k, v);
                }
            }
            for k in default_facts.keys() {
                if s.get(k).is_none() {
                    return Err(format!("{name}: state {} lacks fact {k}", s["id"]));
                }
            }
            if line.len() > 1 {
                state_lines.push(Value::Object(line));
            }
            next_state += 1;
        }
    }
    write(&out.join("blocks.json"), &lines(&block_lines))?;
    write(&out.join("block_states.json"), &lines(&state_lines))?;
    write(
        &out.join("shapes.json"),
        &lines(&as_array(&extracted["shapes"])?),
    )?;
    Ok(())
}

fn facts(state: &Value) -> Map<String, Value> {
    let mut m = state.as_object().cloned().unwrap_or_default();
    m.remove("id");
    m
}

fn items(reports: &Path, extracted: &Value, registries: &Value, out: &Path) -> Result<()> {
    let names = as_array(&registries["minecraft:item"]["entries"])?;
    let ext = as_array(extracted)?;
    if names.len() != ext.len() {
        return Err("item counts of registry and extractor differ".into());
    }
    let mut item_lines = Vec::new();
    for (id, (name, e)) in names.iter().zip(&ext).enumerate() {
        let name = name.as_str().ok_or("item name")?;
        if e["name"] != name {
            return Err(format!(
                "extractor item {id} is {}, expected {name}",
                e["name"]
            ));
        }
        let (ns, path) = name.split_once(':').ok_or("item name")?;
        let comp = read_json(&reports.join(format!("{ns}/components/item/{path}.json")))?;
        let mut m = Map::new();
        m.insert("name".into(), name.into());
        m.insert("id".into(), id.into());
        if let Some(b) = e.get("block") {
            m.insert("block".into(), b.clone());
        }
        m.insert("components".into(), comp["components"].clone());
        item_lines.push(Value::Object(m));
    }
    write(&out.join("items.json"), &lines(&item_lines))
}

fn entities(extracted: &Value, out: &Path) -> Result<()> {
    let with_ids = |v: &Value| -> Result<Vec<Value>> {
        Ok(as_array(v)?
            .into_iter()
            .enumerate()
            .map(|(id, mut e)| {
                if let Some(m) = e.as_object_mut() {
                    m.shift_insert(1, "id".into(), id.into());
                }
                e
            })
            .collect())
    };
    write(
        &out.join("entities.json"),
        &lines(&with_ids(&extracted["entity_types"])?),
    )?;
    write(
        &out.join("attributes.json"),
        &lines(&with_ids(&extracted["attributes"])?),
    )
}

fn dense(what: &str, ids: impl Iterator<Item = u64>) -> Result<()> {
    for (i, id) in ids.enumerate() {
        if id != i as u64 {
            return Err(format!("{what}: protocol ids are not dense at {i}"));
        }
    }
    Ok(())
}

fn obj(v: &Value) -> Result<&Map<String, Value>> {
    v.as_object()
        .ok_or_else(|| "expected a JSON object".to_owned())
}

fn as_array(v: &Value) -> Result<Vec<Value>> {
    v.as_array()
        .cloned()
        .ok_or_else(|| "expected a JSON array".to_owned())
}

/// A JSON array with one compact entry per line.
fn lines(items: &[Value]) -> String {
    let mut s = String::from("[\n");
    for (i, item) in items.iter().enumerate() {
        s.push_str(&item.to_string());
        s.push_str(if i + 1 < items.len() { ",\n" } else { "\n" });
    }
    s.push_str("]\n");
    s
}

fn pretty(v: &Value) -> String {
    let mut s = serde_json::to_string_pretty(v).unwrap_or_default();
    s.push('\n');
    s
}

