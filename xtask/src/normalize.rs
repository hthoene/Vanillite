/// The normalised data of one version, for the change report.
#[derive(Default)]
pub struct Snapshot {
    version: String,
    registries: Value,
    packets: Value,
    blocks: BTreeMap<String, Value>,
    states: usize,
    states_diff: Value,
    shapes: usize,
    items: BTreeMap<String, Value>,
    entities: BTreeMap<String, Value>,
    commands: Value,
    biome_parameters: Value,
}

impl Snapshot {
    /// Loads what exists; a missing directory gives an empty snapshot.
    pub fn load(dir: &Path) -> Self {
        let json = |f: &str| read_json(&dir.join(f)).unwrap_or(Value::Null);
        let by_name = |f: &str| -> BTreeMap<String, Value> {
            json(f)
                .as_array()
                .map(|a| {
                    a.iter()
                        .map(|v| (v["name"].as_str().unwrap_or_default().to_owned(), v.clone()))
                        .collect()
                })
                .unwrap_or_default()
        };
        let len = |f: &str| json(f).as_array().map_or(0, Vec::len);
        Self {
            version: crate::read(&dir.join("version.toml")).unwrap_or_default(),
            registries: json("registries.json"),
            packets: json("packets.json"),
            blocks: by_name("blocks.json"),
            states: json("blocks.json").as_array().map_or(0, |a| {
                a.iter()
                    .filter_map(|b| b["state_count"].as_u64())
                    .sum::<u64>()
            }) as usize,
            shapes: len("shapes.json"),
            items: by_name("items.json"),
            entities: by_name("entities.json"),
            commands: json("commands.json"),
            biome_parameters: json("biome_parameters/overworld.json"),
            states_diff: json("block_states.json"),
        }
    }
}

pub fn change_report(old: &Snapshot, new: &Snapshot) -> String {
    let mut r = String::from("# Vanilla data change report\n\n## Version\n\n```diff\n");
    for line in old.version.lines().filter(|l| !new.version.contains(*l)) {
        let _ = writeln!(r, "- {line}");
    }
    for line in new.version.lines().filter(|l| !old.version.contains(*l)) {
        let _ = writeln!(r, "+ {line}");
    }
    r.push_str("```\n\n## Registries\n\n");
    let empty = Map::new();
    let old_regs = old.registries.as_object().unwrap_or(&empty);
    let new_regs = new.registries.as_object().unwrap_or(&empty);
    let mut any = false;
    for name in union(old_regs.keys(), new_regs.keys()) {
        let o = old_regs.get(&name).map(|r| &r["entries"]);
        let n = new_regs.get(&name).map(|r| &r["entries"]);
        if o != n {
            any = true;
            list_diff(&mut r, &name, o, n);
        }
    }
    if !any {
        r.push_str("no changes\n");
    }
    r.push_str("\n## Packets\n\n");
    any = false;
    for state in ["handshake", "status", "login", "configuration", "play"] {
        for dir in ["clientbound", "serverbound"] {
            let o = old.packets.get(state).and_then(|s| s.get(dir));
            let n = new.packets.get(state).and_then(|s| s.get(dir));
            if o != n {
                any = true;
                list_diff(&mut r, &format!("{state}/{dir}"), o, n);
            }
        }
    }
    if !any {
        r.push_str("no changes\n");
    }
    let _ = writeln!(
        r,
        "\n## Blocks\n\nstates: {} -> {}, shapes: {} -> {}",
        old.states, new.states, old.shapes, new.shapes
    );
    map_diff(&mut r, &old.blocks, &new.blocks);
    r.push_str("\n## Items\n\n");
    map_diff(&mut r, &old.items, &new.items);
    r.push_str("\n## Entity types\n\n");
    map_diff(&mut r, &old.entities, &new.entities);
    let _ = writeln!(
        r,
        "\n## Other\n\n- per-state facts: {}\n- command tree: {}\n- overworld biome parameters: {}",
        changed(&old.states_diff, &new.states_diff),
        changed(&old.commands, &new.commands),
        changed(&old.biome_parameters, &new.biome_parameters)
    );
    r
}

fn changed(a: &Value, b: &Value) -> &'static str {
    if a == b { "unchanged" } else { "changed" }
}

fn union<'a>(
    a: impl Iterator<Item = &'a String>,
    b: impl Iterator<Item = &'a String>,
) -> Vec<String> {
    let mut v: Vec<String> = a.chain(b).cloned().collect();
    v.sort();
    v.dedup();
    v
}

fn list_diff(r: &mut String, what: &str, old: Option<&Value>, new: Option<&Value>) {
    let names = |v: Option<&Value>| -> Vec<String> {
        v.and_then(Value::as_array)
            .map(|a| {
                a.iter()
                    .filter_map(|x| x.as_str().map(str::to_owned))
                    .collect()
            })
            .unwrap_or_default()
    };
    let (o, n) = (names(old), names(new));
    let added: Vec<&String> = n.iter().filter(|x| !o.contains(x)).collect();
    let removed: Vec<&String> = o.iter().filter(|x| !n.contains(x)).collect();
    let moved = n
        .iter()
        .enumerate()
        .filter(|(i, x)| o.iter().position(|y| y == *x).is_some_and(|j| j != *i))
        .count();
    let _ = writeln!(
        r,
        "- `{what}`: {} added {:?}, {} removed {:?}, {moved} renumbered",
        added.len(),
        added,
        removed.len(),
        removed
    );
}

fn map_diff(r: &mut String, old: &BTreeMap<String, Value>, new: &BTreeMap<String, Value>) {
    let added: Vec<&String> = new.keys().filter(|k| !old.contains_key(*k)).collect();
    let removed: Vec<&String> = old.keys().filter(|k| !new.contains_key(*k)).collect();
    let changed: Vec<&String> = new
        .iter()
        .filter(|(k, v)| old.get(*k).is_some_and(|o| strip_id(o) != strip_id(v)))
        .map(|(k, _)| k)
        .collect();
    let _ = writeln!(r, "- added ({}): {added:?}", added.len());
    let _ = writeln!(r, "- removed ({}): {removed:?}", removed.len());
    let _ = writeln!(r, "- changed ({}): {changed:?}", changed.len());
}

/// Ids shift whenever something is added; the report lists those as renumbering, not changes.
fn strip_id(v: &Value) -> Value {
    let mut v = v.clone();
    if let Some(m) = v.as_object_mut() {
        for k in ["id", "first_state", "default_state"] {
            m.remove(k);
        }
    }
    v
}
