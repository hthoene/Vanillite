//! Data of older Minecraft versions for the multi-version layer (`vanillite-multiversion`,
//! architecture 14.3).
//!
//! `cargo xtask multiversion add <id>` extracts an older version and keeps the facts that the
//! translation between it and its successor needs in `data/multiversion/<id>/`:
//!
//! - `version.toml`, `packets.json`, `registries.json`: as in `data/vanilla/`;
//! - `blocks.json`: every block with its first and default state and its properties;
//! - `entities.json`: every entity type with its category and size;
//! - `synchronized.json`: the entries of every synchronised data-driven registry in the
//!   version's built-in data pack (what a client of that version knows by name).
//!
//! `cargo xtask version update <id> --final` keeps the outgoing version the same way, so its
//! clients can still join after the switch. Codegen turns each kept version and its successor
//! (the next kept version, or `data/vanilla/`) into the tables of one adapter step in
//! `crates/vanillite-multiversion/src/generated/`.

use std::collections::{BTreeMap, BTreeSet, HashMap};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use serde_json::{Map, Value};

use crate::vanilla::{self, Extracted};
use crate::{Result, normalize, read, read_json, write};

const HEADER: &str = "// @generated by `cargo xtask codegen` from data/multiversion/ and data/vanilla/. Do not edit.\n";

/// Registries whose numeric ids the network uses; a table is generated for each one whose
/// entries differ between two versions.
const NETWORK_REGISTRIES: &[&str] = &[
    "minecraft:attribute",
    "minecraft:block",
    "minecraft:block_entity_type",
    "minecraft:command_argument_type",
    "minecraft:consume_effect_type",
    "minecraft:custom_stat",
    "minecraft:data_component_type",
    "minecraft:debug_subscription",
    "minecraft:entity_type",
    "minecraft:fluid",
    "minecraft:game_event",
    "minecraft:item",
    "minecraft:map_decoration_type",
    "minecraft:menu",
    "minecraft:mob_effect",
    "minecraft:number_format_type",
    "minecraft:particle_type",
    "minecraft:position_source_type",
    "minecraft:potion",
    "minecraft:recipe_book_category",
    "minecraft:recipe_display",
    "minecraft:slot_display",
    "minecraft:sound_event",
    "minecraft:stat_type",
    "minecraft:villager_profession",
    "minecraft:villager_type",
];

/// Registries whose entries an older version lacks are mapped to the most similar older entry
/// by name (see [`similar`]); in all others they have no counterpart, because the entry's
/// network codec may differ (data components, particles, argument types). Entity types are
/// mapped only to an older type with the same category and size (the same entity class).
const SIMILAR: &[&str] = &[
    "minecraft:block",
    "minecraft:item",
    "minecraft:map_decoration_type",
];

/// Entries whose ids the hand-written step code needs (renamed components, placeholders).
const NAMED: &[(&str, &str)] = &[
    ("minecraft:data_component_type", "minecraft:swing_animation"),
    (
        "minecraft:data_component_type",
        "minecraft:attack_animation",
    ),
    ("minecraft:data_component_type", "minecraft:pot_decorations"),
    ("minecraft:item", "minecraft:brick"),
    ("minecraft:sound_event", "minecraft:intentionally_empty"),
    ("minecraft:slot_display", "minecraft:tag"),
    ("minecraft:slot_display", "minecraft:composite"),
    ("minecraft:slot_display", "minecraft:item"),
];

/// `cargo xtask multiversion add <id>`.
pub fn add(root: &Path, args: &[&str]) -> Result<()> {
    let [id] = args else {
        return Err(crate::USAGE.to_owned());
    };
    let manifest = vanilla::manifest()?;
    let x = vanilla::extract(root, &manifest, Some(id), None)?;
    keep(root, &x)?;
    crate::codegen::run(root, false)
}

/// Keeps the multi-version data of an extracted version in `data/multiversion/<id>/`.
pub fn keep(root: &Path, x: &Extracted) -> Result<()> {
    let id = &x.info.id;
    let normalized = x.work.join("multiversion");
    vanilla::remove_dir(&normalized)?;
    normalize::run(
        &x.generated.join("reports"),
        &x.extracted,
        &x.info,
        &normalized,
    )?;
    let out = root.join("data/multiversion").join(id);
    vanilla::remove_dir(&out)?;
    for file in ["version.toml", "packets.json", "registries.json"] {
        write(&out.join(file), &read(&normalized.join(file))?)?;
    }
    write(
        &out.join("blocks.json"),
        &compact_blocks(&read_json(&normalized.join("blocks.json"))?)?,
    )?;
    write(
        &out.join("entities.json"),
        &compact_entities(&read_json(&normalized.join("entities.json"))?)?,
    )?;
    let dynamic = read_json(&normalized.join("dynamic_registries.json"))?;
    write(
        &out.join("synchronized.json"),
        &synchronized(&x.inner_jar, &dynamic)?,
    )?;
    println!("multiversion: kept {id} in {}", out.display());
    Ok(())
}

/// One line per block: name, first and default state, properties.
fn compact_blocks(blocks: &Value) -> Result<String> {
    let mut lines = Vec::new();
    for b in blocks.as_array().ok_or("blocks.json: expected an array")? {
        let mut o = Map::new();
        for key in ["name", "first_state", "default_state", "properties"] {
            o.insert(key.to_owned(), b[key].clone());
        }
        lines.push(Value::Object(o).to_string());
    }
    Ok(format!("[\n{}\n]\n", lines.join(",\n")))
}

/// One line per entity type: name, category, size.
fn compact_entities(entities: &Value) -> Result<String> {
    let mut lines = Vec::new();
    for e in entities
        .as_array()
        .ok_or("entities.json: expected an array")?
    {
        let mut o = Map::new();
        for key in ENTITY_FACTS {
            o.insert((*key).to_owned(), e[*key].clone());
        }
        lines.push(Value::Object(o).to_string());
    }
    Ok(format!("[\n{}\n]\n", lines.join(",\n")))
}

/// Entity type facts that must match for a fallback type.
const ENTITY_FACTS: &[&str] = &["name", "category", "width", "height", "eye_height"];

/// Entry names of the synchronised registries in the jar's built-in data pack.
fn synchronized(inner_jar: &Path, dynamic: &Value) -> Result<String> {
    let registries: Vec<&str> = dynamic["synchronized"]
        .as_array()
        .ok_or("dynamic_registries.json: no synchronized list")?
        .iter()
        .filter_map(Value::as_str)
        .collect();
    let file =
        std::fs::File::open(inner_jar).map_err(|e| format!("{}: {e}", inner_jar.display()))?;
    let zip = zip::ZipArchive::new(file).map_err(|e| format!("{}: {e}", inner_jar.display()))?;
    let mut out: BTreeMap<&str, BTreeSet<String>> =
        registries.iter().map(|r| (*r, BTreeSet::new())).collect();
    for name in zip.file_names() {
        let Ok(name) = name else { continue };
        let Some(rest) = name
            .strip_prefix("data/minecraft/")
            .and_then(|r| r.strip_suffix(".json"))
        else {
            continue;
        };
        for r in &registries {
            let path = r.trim_start_matches("minecraft:");
            if let Some(entry) = rest.strip_prefix(path).and_then(|e| e.strip_prefix('/'))
                && let Some(set) = out.get_mut(r)
            {
                set.insert(format!("minecraft:{entry}"));
            }
        }
    }
    let mut o = Map::new();
    for (r, entries) in out {
        o.insert(
            r.to_owned(),
            Value::Array(entries.into_iter().map(Value::from).collect()),
        );
    }
    let mut s = serde_json::to_string_pretty(&Value::Object(o)).map_err(|e| e.to_string())?;
    s.push('\n');
    Ok(s)
}

/// A version's facts, from `data/multiversion/<id>/` or `data/vanilla/`.
struct Facts {
    id: String,
    protocol: i64,
    packets: Value,
    registries: Value,
    blocks: Vec<Block>,
    /// Entity type name → facts that must match for a fallback.
    entities: HashMap<String, String>,
    synchronized: Option<Value>,
}

struct Block {
    name: String,
    first_state: usize,
    default_state: usize,
    properties: Vec<(String, Vec<String>)>,
}

impl Block {
    fn state_count(&self) -> usize {
        self.properties.iter().map(|p| p.1.len()).product()
    }

    /// Property values of a state of this block.
    fn values(&self, state: usize) -> Vec<&str> {
        let mut stride = self.state_count();
        let offset = state - self.first_state;
        self.properties
            .iter()
            .map(|(_, values)| {
                stride /= values.len();
                values
                    .get(offset / stride % values.len())
                    .map_or("", String::as_str)
            })
            .collect()
    }
}

impl Facts {
    fn load(dir: &Path) -> Result<Self> {
        let version: toml::Table = read(&dir.join("version.toml"))?
            .parse()
            .map_err(|e| format!("{}: {e}", dir.display()))?;
        let mut blocks = Vec::new();
        for b in read_json(&dir.join("blocks.json"))?
            .as_array()
            .ok_or("blocks.json: expected an array")?
        {
            let usize_of = |k: &str| {
                b[k].as_u64()
                    .and_then(|v| usize::try_from(v).ok())
                    .ok_or_else(|| format!("blocks.json: {k} missing"))
            };
            let properties = b["properties"]
                .as_array()
                .map(|ps| {
                    ps.iter()
                        .map(|p| {
                            (
                                p["name"].as_str().unwrap_or_default().to_owned(),
                                p["values"]
                                    .as_array()
                                    .map(|vs| {
                                        vs.iter()
                                            .map(|v| v.as_str().unwrap_or_default().to_owned())
                                            .collect()
                                    })
                                    .unwrap_or_default(),
                            )
                        })
                        .collect()
                })
                .unwrap_or_default();
            blocks.push(Block {
                name: b["name"].as_str().unwrap_or_default().to_owned(),
                first_state: usize_of("first_state")?,
                default_state: usize_of("default_state")?,
                properties,
            });
        }
        let mut entities = HashMap::new();
        for e in read_json(&dir.join("entities.json"))?
            .as_array()
            .ok_or("entities.json: expected an array")?
        {
            let facts: Vec<String> = ENTITY_FACTS
                .iter()
                .skip(1)
                .map(|k| e[*k].to_string())
                .collect();
            entities.insert(
                e["name"].as_str().unwrap_or_default().to_owned(),
                facts.join(" "),
            );
        }
        let synchronized = dir
            .join("synchronized.json")
            .exists()
            .then(|| read_json(&dir.join("synchronized.json")))
            .transpose()?;
        Ok(Self {
            id: version
                .get("id")
                .and_then(|v| v.as_str())
                .ok_or("version.toml: no id")?
                .to_owned(),
            protocol: version
                .get("protocol")
                .and_then(toml::Value::as_integer)
                .ok_or("version.toml: no protocol")?,
            packets: read_json(&dir.join("packets.json"))?,
            registries: read_json(&dir.join("registries.json"))?,
            blocks,
            entities,
            synchronized,
        })
    }

    fn entries(&self, registry: &str) -> Vec<String> {
        self.registries[registry]["entries"]
            .as_array()
            .map(|a| {
                a.iter()
                    .map(|e| e.as_str().unwrap_or_default().to_owned())
                    .collect()
            })
            .unwrap_or_default()
    }
}

/// The generated files of `crates/vanillite-multiversion/src/generated/`.
pub fn generate(root: &Path) -> Result<Vec<(String, String)>> {
    let dir = root.join("data/multiversion");
    let mut kept: Vec<Facts> = Vec::new();
    if dir.exists() {
        let mut dirs: Vec<PathBuf> = std::fs::read_dir(&dir)
            .map_err(|e| format!("{}: {e}", dir.display()))?
            .filter_map(|e| e.ok().map(|e| e.path()))
            .filter(|p| p.join("version.toml").exists())
            .collect();
        dirs.sort();
        for d in dirs {
            kept.push(Facts::load(&d)?);
        }
    }
    let current = Facts::load(&root.join("data/vanilla"))?;
    kept.retain(|f| f.protocol < current.protocol);
    kept.sort_by_key(|f| f.protocol);

    let mut files = Vec::new();
    let mut module = String::from(HEADER);
    module.push_str(
        "//! Tables of the adapter steps, one module per kept version: ids of that version and of\n\
         //! its successor.\n\n",
    );
    for (i, old) in kept.iter().enumerate() {
        let new = kept.get(i + 1).unwrap_or(&current);
        let name = module_name(&old.id);
        let _ = writeln!(module, "pub mod {name};");
        files.push((format!("{name}.rs"), step(old, new)?));
    }
    files.push(("mod.rs".to_owned(), module));
    Ok(files)
}

/// `26.2` → `v26_2`.
fn module_name(id: &str) -> String {
    let mut s = String::from("v");
    s.extend(
        id.chars()
            .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' }),
    );
    s
}

fn step(old: &Facts, new: &Facts) -> Result<String> {
    let mut o = String::from(HEADER);
    let _ = writeln!(
        o,
        "//! Minecraft {} (protocol {}) ↔ {} (protocol {}).\n\n\
         use crate::table::{{PacketTable, Remap}};\n\n\
         /// Version name of the older side.\npub const ID: &str = {:?};\n\
         /// Protocol version of the older side.\npub const PROTOCOL: i32 = {};\n\
         /// Version name of the newer side.\npub const NEXT_ID: &str = {:?};\n\
         /// Protocol version of the newer side.\npub const NEXT_PROTOCOL: i32 = {};\n",
        old.id, old.protocol, new.id, new.protocol, old.id, old.protocol, new.id, new.protocol
    );

    // Packets: by name per state and direction.
    for (state, dir) in [
        ("login", "clientbound"),
        ("login", "serverbound"),
        ("configuration", "clientbound"),
        ("configuration", "serverbound"),
        ("play", "clientbound"),
        ("play", "serverbound"),
    ] {
        let names = |f: &Facts| -> Vec<String> {
            f.packets[state][dir]
                .as_array()
                .map(|a| {
                    a.iter()
                        .map(|e| e.as_str().unwrap_or_default().to_owned())
                        .collect()
                })
                .unwrap_or_default()
        };
        let (o_names, n_names) = (names(old), names(new));
        let remap = remap_by_name(&o_names, &n_names, |_| None);
        let _ = writeln!(
            o,
            "/// `{state}` packets, {dir}.\npub static {}_{}: PacketTable = PacketTable {{",
            state.to_ascii_uppercase(),
            dir.to_ascii_uppercase()
        );
        write_ids(&mut o, "to_old", &remap.0);
        write_ids(&mut o, "to_new", &remap.1);
        o.push_str("};\n\n");
        for (side, list) in [("old", &o_names), ("new", &n_names)] {
            let _ = writeln!(
                o,
                "/// Ids of the `{state}` {dir} packets of the {} version.\npub mod {side}_{state}_{dir} {{",
                if side == "old" { "older" } else { "newer" }
            );
            for (i, n) in list.iter().enumerate() {
                let _ = writeln!(o, "    pub const {}: i32 = {i};", const_name(n));
            }
            o.push_str("}\n\n");
        }
    }

    // Static registries that differ.
    for registry in NETWORK_REGISTRIES {
        let (oe, ne) = (old.entries(registry), new.entries(registry));
        if oe == ne || oe.is_empty() || ne.is_empty() {
            continue;
        }
        let remap = remap_by_name(&oe, &ne, |name| {
            if SIMILAR.contains(registry) {
                // Blocks and items without a similar older one show as stone.
                similar(name, &oe).or_else(|| oe.iter().position(|e| e == "minecraft:stone"))
            } else if *registry == "minecraft:entity_type" {
                let facts = new.entities.get(name)?;
                let same: Vec<String> = oe
                    .iter()
                    .filter(|o| old.entities.get(*o) == Some(facts))
                    .cloned()
                    .collect();
                let i = similar(name, &same)?;
                oe.iter().position(|o| Some(o) == same.get(i))
            } else {
                None
            }
        });
        let _ = writeln!(
            o,
            "/// `{registry}` ids ({} → {} entries).\npub static {}: Remap = Remap {{",
            oe.len(),
            ne.len(),
            const_name(registry)
        );
        write_ids(&mut o, "to_old", &remap.0);
        write_ids(&mut o, "to_new", &remap.1);
        o.push_str("};\n\n");
        // Names of the newer entries without an exact counterpart (sounds go inline by name).
        let missing: Vec<(usize, &String)> = ne
            .iter()
            .enumerate()
            .filter(|(_, n)| !oe.contains(n))
            .collect();
        let _ = writeln!(
            o,
            "/// Newer `{registry}` entries the older version does not have.\npub static {}_ADDED: &[(u16, &str)] = &[",
            const_name(registry)
        );
        for (i, n) in missing {
            let _ = writeln!(o, "    ({i}, {n:?}),");
        }
        o.push_str("];\n\n");
    }

    // Block states.
    let states = block_states(old, new);
    let _ = writeln!(
        o,
        "/// Block state ids: newer state → older state (same block and property values, or the\n\
         /// closest block), older → newer.\npub static BLOCK_STATE: Remap = Remap {{"
    );
    write_ids(&mut o, "to_old", &states.0);
    write_ids(&mut o, "to_new", &states.1);
    o.push_str("};\n\n");

    // Synchronised registries the older version knows.
    let sync = old
        .synchronized
        .as_ref()
        .ok_or_else(|| format!("data/multiversion/{}: synchronized.json missing", old.id))?;
    o.push_str(
        "/// Entries of the synchronised data-driven registries that the older version has built\n\
         /// in, sorted. Registries it does not know are left out.\n\
         pub static SYNCHRONIZED: &[(&str, &[&str])] = &[\n",
    );
    for (registry, entries) in sync
        .as_object()
        .ok_or("synchronized.json: expected an object")?
    {
        let entries = entries.as_array().cloned().unwrap_or_default();
        let _ = writeln!(o, "    ({registry:?}, &[");
        for e in entries {
            let _ = writeln!(o, "        {e},");
        }
        o.push_str("    ]),\n");
    }
    o.push_str("];\n\n");

    // Static registries of the older version (tags of other registries are not sent to it).
    o.push_str("/// Static registries the older version has.\npub static STATIC_REGISTRIES: &[&str] = &[\n");
    if let Some(regs) = old.registries.as_object() {
        for name in regs.keys() {
            let _ = writeln!(o, "    {name:?},");
        }
    }
    o.push_str("];\n\n");

    // Names of the newer version's entries where the codec depends on the entry (particle
    // options, argument parser properties, stat values) or the entry is special.
    for (registry, name) in [
        ("minecraft:particle_type", "NEW_PARTICLE_TYPES"),
        (
            "minecraft:command_argument_type",
            "NEW_COMMAND_ARGUMENT_TYPES",
        ),
        ("minecraft:stat_type", "NEW_STAT_TYPES"),
        ("minecraft:entity_type", "NEW_ENTITY_TYPES"),
        ("minecraft:data_component_type", "NEW_DATA_COMPONENT_TYPES"),
    ] {
        let _ = writeln!(
            o,
            "\n/// `{registry}` names of the newer version by id.\npub static {name}: &[&str] = &["
        );
        for e in new.entries(registry) {
            let _ = writeln!(o, "    {e:?},");
        }
        o.push_str("];\n");
    }
    // Single entries the hand-written step code refers to, by name on both sides (-1: absent).
    for (registry, name) in NAMED {
        let id = |f: &Facts| {
            f.entries(registry)
                .iter()
                .position(|e| e == name)
                .and_then(|i| i64::try_from(i).ok())
                .unwrap_or(-1)
        };
        let c = format!("{}_{}", const_name(registry), const_name(name));
        let _ = writeln!(
            o,
            "\n/// `{name}` in `{registry}`: older and newer id (-1: absent).\n\
             pub const OLD_{c}: i32 = {};\npub const NEW_{c}: i32 = {};",
            id(old),
            id(new)
        );
    }
    let old_string = old
        .entries("minecraft:command_argument_type")
        .iter()
        .position(|e| e == "brigadier:string")
        .unwrap_or(0);
    let _ = writeln!(
        o,
        "\n/// Id of `brigadier:string` in the older version (stands in for unknown parsers).\n\
         pub const OLD_STRING_PARSER: i32 = {old_string};"
    );
    Ok(o)
}

/// `u16::MAX` stands for "no counterpart".
fn write_ids(o: &mut String, field: &str, ids: &[Option<usize>]) {
    let values: Vec<String> = ids
        .iter()
        .map(|i| i.map_or_else(|| "u16::MAX".to_owned(), |i| i.to_string()))
        .collect();
    let _ = writeln!(o, "    {field}: &[");
    let mut line = String::from("       ");
    for v in values {
        if line.len() + v.len() + 2 > 100 {
            o.push_str(line.trim_end());
            o.push('\n');
            line = String::from("       ");
        }
        line.push(' ');
        line.push_str(&v);
        line.push(',');
    }
    if !line.trim().is_empty() {
        o.push_str(&line);
        o.push('\n');
    }
    o.push_str("    ],\n");
}

/// Maps by name: newer id → older id (with `fallback` for names the older version lacks) and
/// older id → newer id.
fn remap_by_name(
    old: &[String],
    new: &[String],
    fallback: impl Fn(&str) -> Option<usize>,
) -> (Vec<Option<usize>>, Vec<Option<usize>>) {
    let old_ids: HashMap<&str, usize> = old
        .iter()
        .enumerate()
        .map(|(i, n)| (n.as_str(), i))
        .collect();
    let new_ids: HashMap<&str, usize> = new
        .iter()
        .enumerate()
        .map(|(i, n)| (n.as_str(), i))
        .collect();
    let to_old = new
        .iter()
        .map(|n| old_ids.get(n.as_str()).copied().or_else(|| fallback(n)))
        .collect();
    let to_new = old
        .iter()
        .map(|n| new_ids.get(n.as_str()).copied())
        .collect();
    (to_old, to_new)
}

/// The closest name in `candidates` for a name they lack: the most trailing `_`-separated words
/// in common (`poplar_planks` → `acacia_planks`, `dappled_forest` → `forest`), the shortest and
/// then alphabetically first name on a tie. Same algorithm as `vanillite_multiversion::similar`.
pub fn similar(name: &str, candidates: &[String]) -> Option<usize> {
    let words = |s: &str| -> Vec<String> {
        s.rsplit(':')
            .next()
            .unwrap_or(s)
            .split(['_', '/'])
            .map(str::to_owned)
            .collect()
    };
    let target = words(name);
    let mut best: Option<(usize, usize, &str, usize)> = None;
    for (i, c) in candidates.iter().enumerate() {
        let cw = words(c);
        let common = target
            .iter()
            .rev()
            .zip(cw.iter().rev())
            .take_while(|(a, b)| a == b)
            .count();
        if common == 0 {
            continue;
        }
        let better = match best {
            None => true,
            Some((bc, bl, bn, _)) => {
                common > bc
                    || (common == bc && (c.len() < bl || (c.len() == bl && c.as_str() < bn)))
            }
        };
        if better {
            best = Some((common, c.len(), c.as_str(), i));
        }
    }
    best.map(|b| b.3)
}

/// Block states by block name and property values; states of blocks the older version lacks
/// go to the closest older block (matching property values where it has them).
fn block_states(old: &Facts, new: &Facts) -> (Vec<Option<usize>>, Vec<Option<usize>>) {
    let old_names: Vec<String> = old.blocks.iter().map(|b| b.name.clone()).collect();
    let old_by_name: HashMap<&str, &Block> =
        old.blocks.iter().map(|b| (b.name.as_str(), b)).collect();
    let new_by_name: HashMap<&str, &Block> =
        new.blocks.iter().map(|b| (b.name.as_str(), b)).collect();
    let old_total = old
        .blocks
        .iter()
        .map(|b| b.first_state + b.state_count())
        .max()
        .unwrap_or(0);
    let new_total = new
        .blocks
        .iter()
        .map(|b| b.first_state + b.state_count())
        .max()
        .unwrap_or(0);

    let state_in = |target: &Block, source: &Block, state: usize| -> usize {
        let values = source.values(state);
        let mut id = target.first_state;
        let mut stride = target.state_count();
        let default = target.values(target.default_state);
        for (i, (pname, pvalues)) in target.properties.iter().enumerate() {
            stride /= pvalues.len();
            let wanted = source
                .properties
                .iter()
                .position(|p| &p.0 == pname)
                .and_then(|j| values.get(j).copied())
                .and_then(|v| pvalues.iter().position(|pv| pv == v))
                .or_else(|| {
                    pvalues
                        .iter()
                        .position(|pv| Some(&pv.as_str()) == default.get(i))
                })
                .unwrap_or(0);
            id += wanted * stride;
        }
        id
    };

    let mut to_old = vec![None; new_total];
    for b in &new.blocks {
        let target = old_by_name
            .get(b.name.as_str())
            .copied()
            .or_else(|| similar(&b.name, &old_names).and_then(|i| old.blocks.get(i)));
        for s in b.first_state..b.first_state + b.state_count() {
            if let Some(slot) = to_old.get_mut(s) {
                *slot = Some(target.map_or(0, |t| state_in(t, b, s)));
            }
        }
    }
    let mut to_new = vec![None; old_total];
    for b in &old.blocks {
        let Some(target) = new_by_name.get(b.name.as_str()) else {
            continue;
        };
        for s in b.first_state..b.first_state + b.state_count() {
            if let Some(slot) = to_new.get_mut(s) {
                *slot = Some(state_in(target, b, s));
            }
        }
    }
    (to_old, to_new)
}

/// `minecraft:add_entity` → `ADD_ENTITY`.
fn const_name(name: &str) -> String {
    let path = name.strip_prefix("minecraft:").unwrap_or(name);
    let mut s: String = path
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_uppercase()
            } else {
                '_'
            }
        })
        .collect();
    if s.starts_with(|c: char| c.is_ascii_digit()) {
        s.insert(0, '_');
    }
    s
}
